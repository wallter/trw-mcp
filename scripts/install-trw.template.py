class UI:
    """Output helper that adapts to interactive/quiet/script modes."""

    def __init__(self, interactive: bool = False, quiet: bool = False) -> None:
        self.interactive = interactive
        self.quiet = quiet
        self._spinner: _Spinner | None = None
        self._deferred_warnings: list[str] = []
        self._seen_child_warnings: set[str] = set()

    def first_sighting(self, msg: str) -> bool:
        """True the first time *msg* is shown in this install, False for every repeat.

        ``update-project`` runs once per configured client and each run prints the same project-wide
        notices (e.g. ``retired_artifact_present`` for every retired file), so four clients showed
        every notice four times. A repeat adds no information, so it is dropped.
        """
        if msg in self._seen_child_warnings:
            return False
        self._seen_child_warnings.add(msg)
        return True

    def info(self, msg: str) -> None:
        if not self.quiet:
            print(f"{GREEN}[TRW]{NC} {msg}")

    def warn(self, msg: str) -> None:
        print(f"{YELLOW}[TRW]{NC} {msg}")

    def error(self, msg: str) -> None:
        print(f"{RED}[TRW]{NC} {msg}", file=sys.stderr)

    def blank(self) -> None:
        if not self.quiet:
            print()

    def step_header(self, step: int, total: int, label: str) -> None:
        if self.interactive:
            print(f"\n  {BOLD}Step {step}/{total}{NC}  {label}")
        else:
            self.info(label)

    def step_ok(self, msg: str) -> None:
        self.halt_spinner()
        if self.interactive:
            print(f"            {GREEN}\u2713{NC} {msg}")
        elif not self.quiet:
            self.info(msg)

    def step_warn(self, msg: str) -> None:
        self.halt_spinner()
        if self.interactive:
            print(f"            {YELLOW}!{NC} {msg}")
        else:
            self.warn(msg)

    def defer_warn(self, msg: str) -> None:
        """Queue a warning to be shown once the current spinner has stopped.

        A warning printed while the spinner thread is repainting the same line
        is overwritten and lost — which is how ``update-project``'s policy
        refusals (the operator's only signal that their AGENTS.md was left
        stale) disappeared in interactive mode. With no spinner running there is
        nothing to wait for, so the warning is emitted immediately.

        A warning already shown in this install is not shown again (see :meth:`first_sighting`).
        """
        if not self.first_sighting(msg):
            return
        if self._spinner is None:
            self.step_warn(msg)
            return
        self._deferred_warnings.append(msg)

    def flush_deferred_warnings(self) -> None:
        """Emit and clear every queued warning. Idempotent."""
        pending, self._deferred_warnings = self._deferred_warnings, []
        for msg in pending:
            self.step_warn(msg)

    def step_fail(self, msg: str) -> None:
        self.halt_spinner()
        if self.interactive:
            print(f"            {RED}\u2717{NC} {msg}")
        else:
            self.error(msg)

    def hint(self, msg: str) -> None:
        """Show a dim hint line (interactive only)."""
        if self.interactive:
            print(f"    {DIM}{msg}{NC}")

    def doc_link(self, anchor: str) -> None:
        """Show a docs link hint."""
        self.hint(f"Learn more: {DOCS_BASE}/{anchor}")

    def doc_link_url(self, url: str) -> None:
        """Show a docs link hint pointing at an absolute URL.

        Used for links outside the ``/docs`` tree (e.g. the root
        ``/privacy`` route) that ``doc_link`` cannot express.
        """
        self.hint(f"Learn more: {url}")

    # ── Spinner ──────────────────────────────────────────────────────

    def start_spinner(self, msg: str) -> None:
        if not self.interactive:
            return
        self.halt_spinner()  # one spinner at a time: a replaced one would keep repainting forever
        self._spinner = _Spinner(msg)
        self._spinner.start()

    def update_spinner(self, msg: str) -> None:
        if self._spinner is not None:
            self._spinner.message = msg

    def halt_spinner(self) -> None:
        """Stop the running spinner, if any, and clear its line; prints no verdict.

        A verdict line, a new spinner and a prompt all call this first: a spinner left running (an
        exception path that never reached ``stop_spinner``) repaints the last line every 0.1s and erased
        the next prompt, so the install looked hung (operator feedback 2026-10-01).
        """
        if self._spinner is not None:
            self._spinner.stop()
            self._spinner = None
            sys.stdout.write("\r\033[K")
            sys.stdout.flush()

    def stop_spinner(self, success: bool, ok_msg: str, fail_msg: str = "Failed") -> None:
        self.halt_spinner()
        if success:
            self.step_ok(ok_msg)
        else:
            self.step_fail(fail_msg)
        # Warnings the child emitted under the spinner are shown here, after the
        # step's own verdict line, so they survive the repaint.
        self.flush_deferred_warnings()


class _Spinner:
    """Braille-character spinner in a daemon thread."""

    _FRAMES = "\u280b\u2819\u2839\u2838\u283c\u2834\u2826\u2827\u2807\u280f"

    def __init__(self, message: str) -> None:
        self.message = message
        self._stop = threading.Event()
        self._thread: threading.Thread | None = None

    def start(self) -> None:
        self._thread = threading.Thread(target=self._run, daemon=True)
        _LIVE_SPINNERS.add(self)
        self._thread.start()

    def stop(self) -> None:
        self._stop.set()
        _LIVE_SPINNERS.discard(self)
        if self._thread is not None:
            self._thread.join(timeout=2.0)

    def _run(self) -> None:
        idx = 0
        while not self._stop.is_set():
            frame = self._FRAMES[idx % len(self._FRAMES)]
            sys.stdout.write(f"\r\033[K            {frame} {self.message}")
            sys.stdout.flush()
            idx += 1
            self._stop.wait(0.1)


#: Every spinner whose thread may still be repainting; a prompt stops them all before it draws.
_LIVE_SPINNERS: set[_Spinner] = set()


def _halt_live_spinners() -> None:
    """Stop every live spinner and clear its line, so no thread repaints over a prompt."""
    if not _LIVE_SPINNERS:
        return
    for spinner in list(_LIVE_SPINNERS):
        spinner.stop()
    sys.stdout.write("\r\033[K")
    sys.stdout.flush()


