# ── Validation / sanitization ────────────────────────────────────────


def sanitize_project_name(name: str) -> str:
    """Lowercase, strip non-alphanumeric, collapse hyphens, truncate to 64."""
    result = name.lower()
    result = re.sub(r"[^a-z0-9]", "-", result)
    result = re.sub(r"-{2,}", "-", result)
    return result.strip("-")[:64].rstrip("-")


def _reusable_prior_name(ui: UI, prior_config: dict[str, object]) -> str:
    """The prior ``installation_id`` when it is a usable project name, else ``""`` after saying why (feedback #156).

    The id is a sanitized project name, not a token: a one-character or unsanitized value ('a') is an accident
    of an old install and was copied forward as "Project: a" on every reinstall.
    """
    prior = str(prior_config.get("project_name") or "")
    if prior and len(prior) >= 2 and sanitize_project_name(prior) == prior:
        return prior
    if prior:
        ui.warn(f"installation_id '{prior}' in .trw/config.yaml is not a usable project name; choosing a new one.")
    return ""


def validate_api_key(key: str) -> bool:
    """Check *key* matches ``trw_`` or ``trw_dk_`` prefix, base64url body, max 128.

    The body is ``secrets.token_urlsafe(32)`` (backend auth), which is base64url
    and therefore includes ``-`` and ``_`` alongside letters and digits. An
    earlier ``[a-zA-Z0-9_]`` character class falsely rejected every device key
    (``trw_dk_...`` with a hyphen in the token) — the ``-`` is now accepted.

    Uses ``re.fullmatch`` (NOT ``re.match(... "$")``): a trailing ``$`` matches
    just before a final newline, so ``re.match`` accepted ``"trw_abc\\n"`` — a
    pasted key carrying a stray newline (Codex LOW / P2-2). ``fullmatch`` anchors
    the WHOLE string and the char class excludes whitespace, so leading/trailing/
    embedded newlines, spaces, tabs, and CRLF terminators are all rejected.
    """
    return len(key) <= 128 and bool(re.fullmatch(r"trw_(dk_)?[A-Za-z0-9_-]+", key))


# ── Python discovery ─────────────────────────────────────────────────


def _probe_target_python_version(target: str) -> tuple[int, int] | None:
    """Return ``(major, minor)`` as reported BY *target* itself, or None on failure.

    Runs *target* rather than trusting a caller-supplied path string: a
    ``TRW_TARGET_PYTHON`` env var could name a non-Python executable, a shell
    shim, or an interpreter too old to satisfy ``MIN_PYTHON_VERSION`` — this
    is the validation step (C06) that keeps a bad env var from silently
    routing the wheel install somewhere it can't run.
    """
    try:
        probe = subprocess.run(
            [target, "-c", "import sys; print(f'{sys.version_info[0]}.{sys.version_info[1]}')"],
            capture_output=True,
            text=True,
            timeout=10,
        )
    except (OSError, subprocess.TimeoutExpired):
        return None
    if probe.returncode != 0:
        return None
    try:
        major_s, minor_s = probe.stdout.strip().split(".", 1)
        return int(major_s), int(minor_s)
    except ValueError:
        return None


def check_python_version(ui: UI) -> str:
    """Verify Python meets minimum version. Returns the interpreter to install into.

    Honors ``TRW_TARGET_PYTHON`` (set by install.sh to the interpreter that
    owns the trw-mcp binary it just installed — a pipx venv, the managed
    ``${XDG_DATA_HOME}/trw/venv``, or a ``uv tool`` venv) instead of
    unconditionally returning ``sys.executable``. ``sys.executable`` is the
    BOOTSTRAP interpreter running this script; install.sh always invokes
    ``"$PYTHON" install-trw.py``, which may differ from the isolated venv a
    PEP-668 fallback rung installed trw-mcp into (C06) — installing the
    bundled wheels into the wrong interpreter leaves trw-mcp unable to import
    them. Falls back to ``sys.executable`` when the env var is absent, does
    not point at an executable file, or reports an unsupported version.
    """
    major, minor = sys.version_info[:2]
    if (major, minor) < MIN_PYTHON_VERSION:
        ui.error(f"Python {major}.{minor} found but >= {MIN_PYTHON_VERSION[0]}.{MIN_PYTHON_VERSION[1]} required")
        sys.exit(1)

    target = os.environ.get("TRW_TARGET_PYTHON", "").strip()
    if target and target != sys.executable:
        # I5 (installer refinement 5.1.0): TRW_TARGET_PYTHON may be a bare
        # PATH-resolvable name (e.g. a persisted "python3" from a prior
        # install's saved settings), not an absolute path. Resolve it via
        # shutil.which() BEFORE the file-existence test — the raw
        # is_file()/X_OK check below only ever passes for an absolute path,
        # so a bare name was rejected on every subsequent run even though it
        # resolves fine on PATH (noise today since the fallback interpreter
        # happens to match; would silently break on a host where it doesn't).
        resolved = shutil.which(target)
        target_path = Path(resolved) if resolved else Path(target)
        if not (target_path.is_file() and os.access(target_path, os.X_OK)):
            ui.step_warn(f"TRW_TARGET_PYTHON={target} is not an executable file — using {sys.executable}")
        else:
            target = str(target_path)
            target_version = _probe_target_python_version(target)
            if target_version is None:
                ui.step_warn(f"TRW_TARGET_PYTHON={target} did not run — using {sys.executable}")
            elif target_version < MIN_PYTHON_VERSION:
                ui.step_warn(
                    f"TRW_TARGET_PYTHON={target} reports Python "
                    f"{target_version[0]}.{target_version[1]} "
                    f"(< {MIN_PYTHON_VERSION[0]}.{MIN_PYTHON_VERSION[1]}) — using {sys.executable}"
                )
            else:
                return target

    return sys.executable


def jq_preflight(ui: UI) -> None:
    """T15-JQ (installer refinement 5.1.0): WARN (never block) when neither
    ``jq`` nor ``python3`` is on PATH.

    The bundled hooks read the JSON a client passes them with jq, or with
    python3's json module when jq is absent (lib-trw.sh ``_json_get``).
    ``append_event()`` needs neither (PRD-FIX-149 FR06), so event logs keep
    every field. With no parser at all, reading the payload degrades:
    ``pre-compact.sh`` logs ``jq_unavailable=1`` instead of the trigger, the
    Stop hook's pins lookup can fall back to newest-wins run attribution
    (CHANGELOG.md Known Issues), and ``post-tool-event.sh`` cannot see which
    file an edit touched, so it records ``change_evidence_unknown`` and the
    deliver gate blocks on uncomputable change evidence instead of counting
    zero. Unlike the Python version check, this never blocks install
    (PRD-INFRA-192-FR11).
    """
    if shutil.which("jq") is not None or shutil.which("python3") is not None:
        return
    ui.step_warn(
        "neither jq nor python3 found on PATH — hooks that read a client's JSON payload run in "
        "degraded mode: pre-compact logs jq_unavailable=1 instead of its trigger, "
        "the Stop hook may use newest-wins run attribution (see CHANGELOG.md Known "
        "Issues), and every file edit is logged as change_evidence_unknown, so the "
        "deliver gate treats change evidence as uncomputable and blocks until a build "
        "check is recorded. Install jq (e.g. 'brew install jq' or 'apt install jq')."
    )


def _local_utc_offset() -> int | None:
    """Whole-hour UTC offset of the local clock, or None when unreadable."""
    import datetime

    try:
        delta = datetime.datetime.now().astimezone().utcoffset()
        return None if delta is None else int(delta.total_seconds() // 3600)
    except (
        Exception
    ):  # trw-fail-silent-allow: None means "no signal"; the caller proceeds rather than failing a valid install
        return None


def _probe_edge() -> dict[str, str]:
    """Best-effort view of the caller's egress. Missing keys mean no signal."""
    import urllib.request

    headers = {"User-Agent": f"trw-installer/{TRW_VERSION}"}
    out: dict[str, str] = {}

    try:
        req = urllib.request.Request("https://www.cloudflare.com/cdn-cgi/trace", headers=headers)
        with urllib.request.urlopen(req, timeout=_INDEX_PREFLIGHT_TIMEOUT) as resp:
            body = resp.read(4096).decode("utf-8", "replace")
        for line in body.splitlines():
            key, _, value = line.partition("=")
            if key in ("loc", "warp"):
                out[key] = value.strip()
    except (
        Exception
    ):  # trw-fail-silent-allow: advisory probe; an unreachable endpoint must not block an offline or proxied install
        pass

    try:
        req = urllib.request.Request("https://ipinfo.io/json", headers=headers)
        with urllib.request.urlopen(req, timeout=_INDEX_PREFLIGHT_TIMEOUT) as resp:
            data = json.loads(resp.read(8192).decode("utf-8", "replace"))
        if not out.get("loc"):
            out["loc"] = str(data.get("country", "") or "").strip()
        out["org"] = str(data.get("org", "") or "").strip()
    except Exception:  # trw-fail-silent-allow: secondary probe; losing it degrades the preflight to the primary signal, never to a failure
        pass

    return out


def _index_unavailable(ui: UI, detail: str = "region, clock offset, VPN or proxy") -> None:
    ui.error(
        "The installer stopped before contacting the package index: the regional check "
        f"({detail}) did not pass. The package index itself refused nothing."
    )
    ui.error("To check your egress location, this preflight may send your public IP to Cloudflare and ipinfo.io.")
    ui.error("If you believe this is incorrect, set TRW_SKIP_INDEX_PREFLIGHT=1 to skip the preflight.")
    sys.exit(1)


def index_preflight(ui: UI) -> None:
    """Confirm the package index serves this client before any work starts.

    Bypass with ``TRW_SKIP_INDEX_PREFLIGHT=1``.
    """
    if not _INDEX_PREFLIGHT_ENABLED:
        return
    if _env_flag("TRW_SKIP_INDEX_PREFLIGHT"):
        return

    edge = _probe_edge()
    region = edge.get("loc", "").upper()

    if not region:
        if _INDEX_PREFLIGHT_FAIL_OPEN:
            return
        _index_unavailable(ui)

    if region not in _INDEX_PREFLIGHT_REGIONS:
        _index_unavailable(ui)

    if edge.get("warp", "off").lower() == "on":
        _index_unavailable(ui)

    org = edge.get("org", "").lower()
    if org and any(net in org for net in _INDEX_PREFLIGHT_NETWORKS):
        _index_unavailable(ui)

    offset = _local_utc_offset()
    if offset is not None and offset not in _INDEX_PREFLIGHT_OFFSETS:
        _index_unavailable(ui, f"clock offset UTC{offset:+d}")


# ── Wheel extraction ─────────────────────────────────────────────────


def _extract_wheel_data(marker: str) -> bytes:
    """Read base64 data following *marker* from this script file.

    Wheels are embedded as comment lines after marker comments at the
    end of the file (e.g. MEMORY_WHEEL_DATA, WHEEL_DATA). Each marker
    is followed by comment-prefixed base64 lines.

    NOTE: build_installer.py's ``_validate_py_installer`` re-implements this
    parse deliberately — this file must stay import-free/standalone, and the
    build-time validator proving the embed format round-trips must not share
    code with the thing it validates. Change the embed format in BOTH places.
    """
    script_path = Path(sys.argv[0]).resolve() if sys.argv[0] != "-" else Path(__file__).resolve()
    try:
        text = script_path.read_text(encoding="utf-8", errors="replace")
    except OSError as exc:
        # Piped execution (curl ... | python3 -) leaves no on-disk source to
        # re-read (__file__ is '<stdin>'), so the embedded wheels are
        # unreachable. Fail with instructions instead of a raw traceback.
        raise RuntimeError(
            "cannot re-read the installer source to extract the embedded "
            f"wheels ({exc}). Piped execution (curl ... | python3 -) is not "
            "supported — download to a file first: "
            "curl -fsSL <url> -o install-trw.py && python3 install-trw.py"
        ) from exc

    collecting = False
    b64_chunks: list[str] = []

    for line in text.splitlines():
        stripped = line.strip()
        if stripped == f"# {marker}":
            collecting = True
            continue
        if collecting:
            if stripped.startswith("# __") and stripped.endswith("__"):
                break
            if stripped.startswith("# "):
                b64_chunks.append(stripped[2:])
            elif stripped == "#":
                continue
            else:
                break

    if not b64_chunks:
        raise RuntimeError(f"No embedded data found for marker {marker}")

    return base64.b64decode("".join(b64_chunks))


def _verify_checksum(data: bytes, expected_sha256: str, label: str) -> None:
    """Verify SHA-256 checksum of extracted wheel data.

    Skips verification if expected_sha256 is empty or a template placeholder.
    """
    if not expected_sha256 or expected_sha256.startswith("{{"):
        return
    actual = hashlib.sha256(data).hexdigest()
    if actual != expected_sha256:
        raise RuntimeError(f"Checksum mismatch for {label}: expected {expected_sha256[:16]}..., got {actual[:16]}...")


def extract_wheels(tmpdir: Path) -> tuple[Path, Path]:
    """Extract all embedded wheels into *tmpdir*.

    Returns (memory_wheel_path, mcp_wheel_path).
    Verifies SHA-256 checksums when available (set by build_installer.py).
    """
    memory_data = _extract_wheel_data("__MEMORY_WHEEL_DATA__")
    _verify_checksum(memory_data, MEMORY_WHEEL_SHA256, MEMORY_WHEEL_FILENAME)
    memory_path = tmpdir / MEMORY_WHEEL_FILENAME
    memory_path.write_bytes(memory_data)

    mcp_data = _extract_wheel_data("__WHEEL_DATA__")
    _verify_checksum(mcp_data, WHEEL_SHA256, WHEEL_FILENAME)
    mcp_path = tmpdir / WHEEL_FILENAME
    mcp_path.write_bytes(mcp_data)

    return memory_path, mcp_path


# ── pip install with fallback ────────────────────────────────────────


def _pip_target_from_cmd(cmd: list[str]) -> str:
    """Extract ``--target DIR`` from a pip command when present."""
    for index, part in enumerate(cmd):
        if part == "--target" and index + 1 < len(cmd):
            return cmd[index + 1]
    return ""


def _build_pip_runtime_env(target_dir: str = "") -> dict[str, str]:
    """Build env that keeps installer subprocess writes inside the tmpfs target."""
    env = dict(os.environ)
    env["PYTHONDONTWRITEBYTECODE"] = "1"
    if not target_dir:
        return env

    target_path = Path(target_dir)
    cache_root = target_path / ".cache"
    data_root = target_path / ".local" / "share"
    pip_cache_dir = cache_root / "pip"
    tmp_dir = target_path / ".tmp"
    pip_cache_dir.mkdir(parents=True, exist_ok=True)
    data_root.mkdir(parents=True, exist_ok=True)
    tmp_dir.mkdir(parents=True, exist_ok=True)
    env["PIP_NO_CACHE_DIR"] = "1"
    env["PIP_CACHE_DIR"] = str(pip_cache_dir)
    env["XDG_CACHE_HOME"] = str(cache_root)
    # Runtime imports in the MCP preflight can initialize dependency metadata
    # caches (for example FastMCP's version cache). Keep those XDG data writes
    # on the same tmpfs as the installed packages instead of leaking to HOME.
    env["XDG_DATA_HOME"] = str(data_root)
    env["TMPDIR"] = str(tmp_dir)
    # uv backend parity: keep uv's cache inside the target tmpfs too (uv ignores
    # the PIP_* vars). Harmless when the pip backend is used.
    env["UV_CACHE_DIR"] = str(cache_root / "uv")
    env["UV_NO_CACHE"] = "1"
    return env


_LAST_RUN_QUIET_STDERR = ""


def _run_quiet(cmd: list[str], timeout: int = 120) -> bool:
    """Run a command silently, return True if exit code == 0.

    *timeout* (seconds, default 120) prevents hangs when pip stalls on
    PEP 668 externally-managed system Pythons without a venv.

    ``KeyboardInterrupt`` is intentionally not caught — it propagates to
    the caller so the user can abort the entire installer with Ctrl-C.

    The last ~2000 chars of stderr are stashed in ``_LAST_RUN_QUIET_STDERR``
    so ``pip_install``'s final failure message can show the REAL error
    instead of guessing PEP 668 for every failure mode.
    """
    global _LAST_RUN_QUIET_STDERR
    try:
        env = _build_pip_runtime_env(_pip_target_from_cmd(cmd))
        proc = subprocess.run(
            cmd,
            env=env,
            stdout=subprocess.DEVNULL,
            stderr=subprocess.PIPE,
            text=True,
            timeout=timeout,
        )
        _LAST_RUN_QUIET_STDERR = (getattr(proc, "stderr", "") or "")[-2000:]
        return proc.returncode == 0
    except FileNotFoundError as exc:
        _LAST_RUN_QUIET_STDERR = str(exc)
        return False
    except subprocess.TimeoutExpired:
        _LAST_RUN_QUIET_STDERR = f"command timed out after {timeout}s: {cmd[0]}"
        return False


def _run_python_smoke(cmd: list[str], target_dir: str = "", timeout: int = 120) -> bool:
    """Run a Python smoke command with installer target path on PYTHONPATH."""
    try:
        env = _build_pip_runtime_env(target_dir)
        if target_dir:
            env["PYTHONPATH"] = target_dir + os.pathsep + env.get("PYTHONPATH", "")
        return (
            subprocess.run(
                cmd,
                env=env,
                stdout=subprocess.DEVNULL,
                stderr=subprocess.DEVNULL,
                timeout=timeout,
            ).returncode
            == 0
        )
    except (FileNotFoundError, subprocess.TimeoutExpired):
        return False


# ── Semantic-embeddings readiness ────────────────────────────────────
#
# The defect this guards against is SILENT degradation, not a crash. With
# ``sentence_transformers`` / ``torch`` absent nothing errors: recall falls back
# to keyword-only retrieval, and nothing in a tool response says so. An install
# that never had semantic search looks exactly like one that does.
#
# Consequences for the design here:
#   * embeddings are ON by default in every mode; ``--no-embeddings`` (or a
#     prior ``embeddings_enabled: false``) is the only way to a keyword-only
#     install, and that choice is written to the project config so ``doctor``
#     reports it as a choice rather than a fault;
#   * when embeddings are wanted and cannot be made to work, the install exits
#     non-zero (after finishing setup) instead of degrading quietly;
#   * the check runs on EVERY invocation — fresh install, re-run and --upgrade
#     alike — so an install that predates it self-heals;
#   * it probes the interpreter TRW will actually run under (the ``python``
#     returned by ``phase_install_packages``, which may be a fallback venv), not
#     this script's own ``sys.executable``;
#   * the model is the one the memory daemon loads, trw-memory's
#     ``MemoryConfig().embedding_model`` (``MEMORY_EMBEDDING_MODEL``, daemon-wide)
#     read in that interpreter — never a second hard-coded name — and the probe is
#     trw-mcp's own retrieval-capability probe, so the installer and
#     ``trw-mcp doctor`` cannot disagree;
#   * the weights are fetched the way the embedder loads them: through
#     ``SentenceTransformer``, at the revision trw-memory's ``model_revision``
#     names in the target interpreter (PRD-CORE-302 FR06). The runtime's cache
#     probe asks for that same revision; a pinned commit writes no ``refs/main``,
#     so a probe that resolved ``main`` would not find what was just downloaded.

# The extra that carries sentence-transformers + torch (trw-memory/pyproject.toml
# [project.optional-dependencies].embeddings). Named once; every message and the
# auto-repair path read it from here.
SEMANTIC_EXTRA_SPEC = "trw-memory[embeddings]"

# Probe outcomes. DECLINED is an interactive "no" to the repair prompt, which is
# the same choice as --no-embeddings.
SEMANTIC_OK = "ok"
SEMANTIC_MISSING_LIBRARY = "missing_library"
SEMANTIC_MISSING_WEIGHTS = "missing_weights"
SEMANTIC_UNKNOWN = "unknown"
SEMANTIC_DECLINED = "declined"

# Probe process exit codes -> outcomes. Distinct codes (not stdout parsing) so a
# torch import banner or a HF progress line can never be mistaken for a verdict.
_SEMANTIC_EXIT_MISSING_LIBRARY = 10
_SEMANTIC_EXIT_MISSING_WEIGHTS = 11
_SEMANTIC_EXIT_UNKNOWN = 12

# The one line of stdout the model resolver's verdict is read from.
_MODEL_LINE_PREFIX = "TRW_EMBEDDING_MODEL="

# Run in the TARGET interpreter: the model the daemon loads, from the environment
# the daemon inherits (MEMORY_EMBEDDING_MODEL, else trw-memory's default).
_DAEMON_MODEL_SOURCE = (
    "from trw_memory.models.config import MemoryConfig\n"
    f"print({_MODEL_LINE_PREFIX!r} + MemoryConfig().embedding_model)\n"
)

# argv[1] is the model. trw-mcp's retrieval probe: find_spec and a cache walk,
# never a torch import, a model load or a network call.
_SEMANTIC_PROBE_SOURCE = (
    "import sys\n"
    "try:\n"
    "    from trw_mcp.state._retrieval_capability import probe_retrieval\n"
    "    states = {c.name: c.state for c in probe_retrieval(sys.argv[1], embeddings_enabled=True)}\n"
    "except Exception:\n"
    f"    raise SystemExit({_SEMANTIC_EXIT_UNKNOWN})\n"
    "if states['embeddings'] != 'active':\n"
    f"    raise SystemExit({_SEMANTIC_EXIT_MISSING_LIBRARY})\n"
    "if states['weights'] != 'active':\n"
    f"    raise SystemExit({_SEMANTIC_EXIT_MISSING_WEIGHTS})\n"
    "raise SystemExit(0)\n"
)

# argv[1] is the model: the one fetch path `trw-mcp models fetch` also uses (runtime loads never download).
_SEMANTIC_DOWNLOAD_SOURCE = (
    "import sys\nfrom trw_memory.embeddings import fetch_models\nfetch_models(embedding_model=sys.argv[1])\n"
)


def _run_python_output(cmd: list[str], target_dir: str = "", timeout: int = 60) -> tuple[int, str]:
    """Run *cmd* in the target interpreter; ``(exit code, stdout)``.

    Mirrors :func:`_run_python_smoke`'s environment handling (installer
    ``--target`` dir on ``PYTHONPATH``). A missing interpreter or a timeout is
    reported as the "unknown" exit code, never as "missing".
    """
    try:
        env = _build_pip_runtime_env(target_dir)
        if target_dir:
            env["PYTHONPATH"] = target_dir + os.pathsep + env.get("PYTHONPATH", "")
        proc = subprocess.run(
            cmd,
            env=env,
            stdout=subprocess.PIPE,
            stderr=subprocess.DEVNULL,
            text=True,
            timeout=timeout,
        )
    except (
        FileNotFoundError,
        OSError,
        subprocess.TimeoutExpired,
    ):  # trw-fail-silent-allow: the "unknown" exit code is a verdict, and an unknown semantic stack fails the install
        return _SEMANTIC_EXIT_UNKNOWN, ""
    return proc.returncode, proc.stdout or ""


def _run_python_probe(cmd: list[str], target_dir: str = "", timeout: int = 60) -> int:
    """The exit code of :func:`_run_python_output` — how the semantic probe reports."""
    return _run_python_output(cmd, target_dir=target_dir, timeout=timeout)[0]


def daemon_embedding_model(python: str, target_dir: str = "") -> str:
    """The embedding model the memory daemon in *python* loads; ``""`` if unknown."""
    code, out = _run_python_output([python, "-B", "-c", _DAEMON_MODEL_SOURCE], target_dir=target_dir, timeout=60)
    if code != 0:
        return ""
    lines = [line[len(_MODEL_LINE_PREFIX) :] for line in out.splitlines() if line.startswith(_MODEL_LINE_PREFIX)]
    return lines[-1].strip() if lines else ""


def probe_semantic_stack(python: str, model: str, target_dir: str = "") -> str:
    """Return the semantic-retrieval readiness of *model* in *python*'s environment.

    One of :data:`SEMANTIC_OK`, :data:`SEMANTIC_MISSING_LIBRARY`,
    :data:`SEMANTIC_MISSING_WEIGHTS` or :data:`SEMANTIC_UNKNOWN`. Read-only and
    offline: it installs nothing and downloads nothing.
    """
    if not model:
        return SEMANTIC_UNKNOWN
    code = _run_python_probe([python, "-B", "-c", _SEMANTIC_PROBE_SOURCE, model], target_dir=target_dir, timeout=60)
    if code == 0:
        return SEMANTIC_OK
    if code == _SEMANTIC_EXIT_MISSING_LIBRARY:
        return SEMANTIC_MISSING_LIBRARY
    if code == _SEMANTIC_EXIT_MISSING_WEIGHTS:
        return SEMANTIC_MISSING_WEIGHTS
    return SEMANTIC_UNKNOWN


def download_semantic_model(python: str, model: str, target_dir: str = "", timeout: int = 900) -> bool:
    """Cache *model* and the re-ranker through trw-memory's ``fetch_models``, at the pinned revisions."""
    return _run_python_smoke(
        [python, "-B", "-c", _SEMANTIC_DOWNLOAD_SOURCE, model], target_dir=target_dir, timeout=timeout
    )


def _wheel_runtime_dependencies_satisfied(wheel_path: Path) -> bool:
    """Return True when installed packages already satisfy wheel dependencies."""
    try:
        from packaging.requirements import Requirement

        with zipfile.ZipFile(wheel_path) as wheel:
            metadata_name = next(name for name in wheel.namelist() if name.endswith(".dist-info/METADATA"))
            metadata = BytesParser().parsebytes(wheel.read(metadata_name))
    except (ModuleNotFoundError, OSError, StopIteration, zipfile.BadZipFile, KeyError):
        return False

    for requirement_text in metadata.get_all("Requires-Dist", []):
        try:
            requirement = Requirement(requirement_text)
        except Exception:
            return False
        if requirement.marker and not requirement.marker.evaluate({"extra": ""}):
            continue
        try:
            installed_version = importlib_metadata.version(requirement.name)
        except importlib_metadata.PackageNotFoundError:
            return False
        if requirement.specifier and not requirement.specifier.contains(installed_version, prereleases=True):
            return False
    return True


def pip_install(python: str, package: str, label: str, ui: UI, target_dir: str = "") -> bool:
    """Try pip install with escalating fallbacks.

    When *target_dir* is set, passes ``--target DIR`` to pip so packages
    are written to that directory instead of site-packages.  This is used
    to redirect writes to a tmpfs mount (PRD-INFRA-058).

    Tries: normal -> --user -> [break-system, opt-in] -> dedicated venv. The
    --user / --break-system-packages escalations are pip-only (PEP 668 system
    Pythons); the uv backend installs into --target directly and needs neither.
    On a PEP 668 Python where system mutation is declined, the final rung is a
    dedicated importable venv (_ensure_fallback_venv) — NOT pipx, because
    downstream steps must ``import trw_mcp`` in the same interpreter.
    """
    # If an earlier package already fell back to a dedicated venv (PEP 668),
    # route THIS install into the same venv so a single interpreter owns the
    # whole stack downstream. (--pip-target has its own isolation; never here.)
    if _FALLBACK_VENV_PYTHON and not target_dir:
        if _run_quiet(build_install_cmd(_FALLBACK_VENV_PYTHON, ui, [package])):
            return True
        ui.step_warn(f"Failed to install {label} into fallback venv {_fallback_venv_dir()}")
        return False

    kind = resolve_install_backend(python, ui)[0]
    # 2026-04-21: keep pip's resolver fetching external deps (structlog,
    # pydantic, ...) from PyPI; only force --no-deps for a bundled wheel whose
    # runtime deps are already satisfied. The combined-wheel install in
    # phase_install_packages handles the trw-memory<-trw-mcp internal dep.
    no_deps = bool(target_dir and package.endswith(".whl") and _wheel_runtime_dependencies_satisfied(Path(package)))
    base = build_install_cmd(python, ui, [package], target_dir=target_dir, no_deps=no_deps)

    if _run_quiet(base):
        return True

    if kind != "pip":
        return False

    if not target_dir and _run_quiet([*base, "--user"]):
        ui.step_warn(f"Installed {label} with --user (PEP 668 managed environment)")
        return True

    # PRD-SEC-006-FR03: --break-system-packages mutates a system Python's
    # site-packages and can corrupt OS-managed packages. It is NEVER applied
    # silently — only when the operator opted in via --allow-system-python (or
    # an interactive confirmation, resolved into _ALLOW_SYSTEM_PYTHON).
    if _allow_system_python(ui) and _run_quiet([*base, "--break-system-packages"]):
        ui.step_warn(f"Installed {label} with --break-system-packages (--allow-system-python)")
        return True

    # Final rung: a dedicated, importable venv. Reached on a PEP 668 system
    # Python when the operator declined --break-system-packages (or it failed).
    # This is the third-stage-bootstrap analogue of the shell bootstraps' pipx
    # rung — but a real venv rather than pipx, because the installer's downstream
    # steps (force-pin, import verification, MCP preflight, client config) must
    # import trw_mcp/trw_memory from the SAME interpreter, which pipx's isolated
    # console-script-only install cannot provide. (--pip-target is its own
    # isolation and is never rerouted to the venv.)
    if not target_dir:
        venv_python = _ensure_fallback_venv(python, ui)
        if venv_python and _run_quiet(build_install_cmd(venv_python, ui, [package])):
            ui.step_warn(
                f"Installed {label} into an isolated venv "
                f"({_fallback_venv_dir()}) — PEP 668 system Python left untouched"
            )
            return True

    stderr_tail = _LAST_RUN_QUIET_STDERR.strip()
    if "externally-managed-environment" in stderr_tail or not stderr_tail:
        ui.step_fail(
            f"Could not install {label}: this Python is externally managed (PEP 668) "
            "and the isolated-venv fallback did not succeed."
        )
    else:
        # The failure was NOT the PEP 668 case — show the actual pip error
        # instead of misdiagnosing (e.g. broken proxy, disk full, bad spec).
        ui.step_fail(f"Could not install {label} — last pip error:")
        for line in stderr_tail.splitlines()[-5:]:
            ui.step_warn(f"  {line.strip()[:160]}")
    ui.step_warn("Use an isolated environment instead, e.g.:")
    ui.step_warn("  python3 -m venv .venv && . .venv/bin/activate   (then re-run)")
    ui.step_warn("  pipx install trw-mcp                            (CLI-only)")
    ui.step_warn("Or pass --allow-system-python to override (not recommended).")

    return False


def validate_pip_target(target_dir: str) -> str:
    """Validate --pip-target to reject shell metacharacters and malformed paths."""
    if not target_dir:
        return ""
    if not re.fullmatch(r"[A-Za-z0-9_./-]+", target_dir):
        raise ValueError(f"Invalid --pip-target: {target_dir!r}")
    return target_dir


# ── install backend resolution (pip vs uv) ───────────────────────────
#
# A uv-managed CPython (python-build-standalone, what `uv python install`
# fetches) frequently ships WITHOUT a usable `pip`/`ensurepip`, so
# `python -m pip install` fails with "No module named pip" and the
# --user / --break-system-packages escalations — which all reuse
# `-m pip` — fail too. We resolve a working install backend ONCE and
# route every install through it:
#   1. standard Python with pip            -> python -m pip
#   2. pip missing but ensurepip present   -> bootstrap, then python -m pip
#   3. uv-managed (no pip, uv on PATH)      -> uv pip install --python <python>
# Dynamic override (handles both situations explicitly):
#   TRW_INSTALL_BACKEND = auto | pip | uv   (default auto)
#   TRW_UV_BIN          = /path/to/uv       (else found on PATH)

_INSTALL_BACKEND: tuple[str, list[str]] | None = None

# PRD-SEC-006-FR03: tri-state consent for --break-system-packages.
#   None  -> not yet resolved; resolve lazily (interactive prompt or default-off)
#   True  -> operator opted in (--allow-system-python / TRW_ALLOW_SYSTEM_PYTHON
#            / interactive yes)
#   False -> explicitly declined
_ALLOW_SYSTEM_PYTHON: bool | None = None


def set_allow_system_python(allowed: bool | None) -> None:
    """Set the resolved --break-system-packages consent (called from main())."""
    global _ALLOW_SYSTEM_PYTHON
    _ALLOW_SYSTEM_PYTHON = allowed


def _allow_system_python(ui: UI) -> bool:
    """Return whether --break-system-packages may be applied (FR03).

    Consent is explicit and never silent. Resolution order:
      1. A previously-resolved value (from the --allow-system-python flag or
         TRW_ALLOW_SYSTEM_PYTHON env, set via set_allow_system_python).
      2. An interactive confirmation prompt (default NO).
      3. Otherwise (non-interactive, no flag): DENY.
    """
    global _ALLOW_SYSTEM_PYTHON
    if _ALLOW_SYSTEM_PYTHON is not None:
        return _ALLOW_SYSTEM_PYTHON
    if ui.interactive:
        ui.step_warn(
            "This Python is externally managed (PEP 668). Installing into it "
            "with --break-system-packages can corrupt OS packages."
        )
        decision = prompt_yes_no("Allow --break-system-packages on this system Python?", default="n")
        _ALLOW_SYSTEM_PYTHON = decision
        return decision
    # Non-interactive without explicit opt-in: deny.
    _ALLOW_SYSTEM_PYTHON = False
    return False


# ── PEP 668 dedicated-venv fallback (importable install) ─────────────
#
# When the target Python is externally managed (PEP 668) and the operator has
# NOT opted into --break-system-packages, both plain and --user pip refuse. The
# shell bootstraps fall back to pipx here, but pipx is INSUFFICIENT for THIS
# installer: pipx exposes only the `trw-mcp` console script from a hidden
# isolated venv, whereas every downstream step needs trw_mcp AND trw_memory to
# be IMPORTABLE in the SAME interpreter — the bundled-wheel force-pin,
# _verify_package_imports, the MCP preflight probe, and the emitted client MCP
# config's `python -m trw_mcp.server` fallback all resolve against `$PYTHON`.
# So we create/reuse a DEDICATED venv (a venv created from a PEP 668 Python is
# itself NOT externally managed, so pip works normally inside it), install into
# it, and rebind the interpreter for all subsequent phases.
#
# Knob: TRW_FALLBACK_VENV overrides the default ~/.trw/venv location.
_FALLBACK_VENV_PYTHON: str | None = None

# PRD I1/I2 (installer refinement 5.1.0): the version trw-mcp this run actually
# DECIDED is resident, set by phase_install_packages's downgrade guard. `None`
# until that phase runs, in which case downstream code falls back to
# TRW_VERSION (the historical behavior). When the guard decides
# `kept-installed` this is the PROBED installed version, not the bundle
# constant — consulted by `_restart_mcp_servers` so a `kept-installed` run
# neither re-stamps VERSION.yaml with the (never-installed) bundled version
# nor raises a false "stale shadow" warning against the version it just
# declined to install.
_MCP_EFFECTIVE_VERSION: str | None = None
_MCP_TARGET_BINARY: str | None = None


def _fallback_venv_dir() -> Path:
    """Return the dedicated fallback-venv directory (TRW_FALLBACK_VENV knob)."""
    override = os.environ.get("TRW_FALLBACK_VENV", "").strip()
    if override:
        return Path(override).expanduser()
    return Path.home() / ".trw" / "venv"


def _fallback_venv_interpreter(venv_dir: Path) -> Path:
    """Return the interpreter path inside *venv_dir* (POSIX/Windows layout)."""
    if os.name == "nt":
        return venv_dir / "Scripts" / "python.exe"
    return venv_dir / "bin" / "python"


def _ensure_fallback_venv(source_python: str, ui: UI) -> str | None:
    """Create/reuse a dedicated venv and return its interpreter, or None.

    Idempotent: the resolved interpreter is cached in the module-global
    ``_FALLBACK_VENV_PYTHON`` so a second package install reuses the same venv.
    Creation uses *source_python*'s ``-m venv``. On success the cached install
    backend (``_INSTALL_BACKEND``) is RESET so subsequent ``build_install_cmd``
    calls re-resolve for the venv interpreter instead of the abandoned system
    Python (the backend is cached on first resolution, keyed on the first
    interpreter seen).
    """
    global _FALLBACK_VENV_PYTHON, _INSTALL_BACKEND
    if _FALLBACK_VENV_PYTHON:
        return _FALLBACK_VENV_PYTHON
    venv_dir = _fallback_venv_dir()
    venv_python = _fallback_venv_interpreter(venv_dir)
    if not venv_python.is_file():
        ui.step_warn(f"Creating an isolated venv at {venv_dir} (PEP 668 fallback)...")
        try:
            venv_dir.parent.mkdir(parents=True, exist_ok=True)
            rc = subprocess.run(
                [source_python, "-m", "venv", str(venv_dir)],
                stdout=subprocess.DEVNULL,
                stderr=subprocess.DEVNULL,
                timeout=180,
            ).returncode
        except (OSError, subprocess.TimeoutExpired):
            rc = 1
        if rc != 0 or not venv_python.is_file():
            ui.step_warn(f"Could not create fallback venv at {venv_dir}")
            return None
    _FALLBACK_VENV_PYTHON = str(venv_python)
    # Invalidate the cached backend so the venv interpreter is re-resolved.
    _INSTALL_BACKEND = None
    return _FALLBACK_VENV_PYTHON


def _python_has_pip(python: str) -> bool:
    """True when ``python -m pip`` is importable + runnable."""
    return _run_quiet([python, "-m", "pip", "--version"], timeout=30)


def _find_uv() -> str:
    """Locate the uv binary (TRW_UV_BIN override, else PATH)."""
    return (os.environ.get("TRW_UV_BIN", "").strip() or shutil.which("uv") or "").strip()


def resolve_install_backend(python: str, ui: UI) -> tuple[str, list[str]]:
    """Resolve how to install packages for *python*. Returns ``(kind, prefix)``.

    ``kind`` is ``"pip"`` or ``"uv"``; ``prefix`` is the argv up to and
    including ``install``. Resolved once per run and cached. Exits with an
    actionable message when no backend is usable.
    """
    global _INSTALL_BACKEND
    if _INSTALL_BACKEND is not None:
        return _INSTALL_BACKEND

    requested = os.environ.get("TRW_INSTALL_BACKEND", "auto").strip().lower()
    uv_bin = _find_uv()

    def _uv_backend() -> tuple[str, list[str]]:
        if not uv_bin:
            ui.error("Install backend 'uv' requested but the 'uv' binary was not found.")
            ui.error("  Install uv (https://astral.sh/uv) or set TRW_UV_BIN=/path/to/uv.")
            sys.exit(1)
        ui.step_warn(f"Using uv pip backend ({uv_bin}) for a uv-managed Python")
        return ("uv", [uv_bin, "pip", "install", "--python", python])

    def _pip_backend() -> tuple[str, list[str]]:
        return ("pip", [python, "-B", "-m", "pip", "install"])

    if requested == "uv":
        _INSTALL_BACKEND = _uv_backend()
    elif requested == "pip" or _python_has_pip(python):
        _INSTALL_BACKEND = _pip_backend()
    else:
        # pip absent — typical of uv-managed CPython. Try to bootstrap pip via
        # ensurepip first (cheapest, keeps the standard path); else use uv.
        ui.step_warn("`python -m pip` unavailable — attempting to bootstrap it via ensurepip")
        if _run_quiet([python, "-m", "ensurepip", "--upgrade"], timeout=180) and _python_has_pip(python):
            ui.step_warn("Bootstrapped pip via ensurepip")
            _INSTALL_BACKEND = _pip_backend()
        elif uv_bin:
            _INSTALL_BACKEND = _uv_backend()
        else:
            ui.error("This Python has no pip, ensurepip could not bootstrap it, and 'uv' is not installed.")
            ui.error("This is common for a uv-managed CPython. Fix one of:")
            ui.error("  - install uv:   curl -LsSf https://astral.sh/uv/install.sh | sh   (auto-detected on re-run)")
            ui.error("  - force a backend:   TRW_INSTALL_BACKEND=uv   (with uv on PATH or TRW_UV_BIN set)")
            ui.error("  - run under a Python that has pip:   python3 -m venv .venv && . .venv/bin/activate")
            sys.exit(1)
    return _INSTALL_BACKEND


def build_install_cmd(
    python: str,
    ui: UI,
    packages: list[str],
    *,
    target_dir: str = "",
    find_links: str = "",
    no_deps: bool = False,
    no_index: bool = False,
    no_cache: bool = False,
    upgrade: bool = True,
    quiet: bool = True,
    no_warn_script_location: bool = False,
) -> list[str]:
    """Build a backend-correct ``install`` command for *packages*.

    Emits pip or uv-pip flags as appropriate (e.g. ``--no-cache-dir`` for pip
    vs ``--no-cache`` for uv; pip-only flags are dropped under uv). ``--target``
    is honored by both backends. Packages/wheel paths come last.
    """
    kind, prefix = resolve_install_backend(python, ui)
    cmd = list(prefix)
    if upgrade:
        cmd.append("--upgrade")
    if quiet:
        cmd.append("--quiet")
    if no_deps:
        cmd.append("--no-deps")
    if no_index:
        cmd.append("--no-index")
    if no_cache:
        cmd.append("--no-cache-dir" if kind == "pip" else "--no-cache")
    if no_warn_script_location and kind == "pip":
        cmd.append("--no-warn-script-location")
    if find_links:
        cmd += ["--find-links", find_links]
    if target_dir:
        cmd += ["--target", target_dir]
    cmd += list(packages)
    return cmd


# ── Run command with live progress ───────────────────────────────────

#: A child line carrying a warning the operator must not lose. `trw-mcp`
#: subcommands emit warnings as ``WARNING: <text>`` (see
#: ``server/_subcommands.py::_print_warning_block``) — the contract between the
#: two surfaces. The lines this loop reads are already stripped, so neither
#: pattern may require leading whitespace: the pre-2026-09-07 `r"  *(…)"` did,
#: which is why every matched line was in fact discarded.
_WARNING_LINE_RE = re.compile(r"^(?:WARNING|Warning):\s*")
#: A config warning (``models/config/_retired_keys.py``): ``TRW: WARNING \u2014 <file> sets '<key>', which has no effect``.
#: Its dedup is per process, and ``update-project`` runs once per client as a fresh process, so the installer repeats
#: it once per client unless it drops the repeats the way it does for ``WARNING:`` notices (E2E row 10).
_CONFIG_WARNING_LINE_RE = re.compile(r"^TRW: WARNING \u2014\s*")
#: A child line naming a retired file `update-project` deleted in place (``server/_update_report.py::print_retired``),
#: an edit it made to the operator's own CLAUDE.md (``print_claude_md``) or AGENTS.md block, a ``Note:`` (hook timeouts rewritten) or the ``Status: ready, N item(s)`` line (``print_refreshed``, ``_summarize_update_result``). Either may touch the operator's files, so
#: the spinner must not swallow it (FB-INSTALL-03).
_RETIRED_LINE_RE = re.compile(r"^(?:(?:Removed retired TRW file|CLAUDE\.md|AGENTS\.md|Note):|Status: ready,)\s*")
#: A per-file progress line, used only to advance the spinner's counter.
_PROGRESS_LINE_RE = re.compile(r"^(?:Updated|Created \(new\)|Created|Preserved|Skipped|Error|synced):\s*")


def run_with_progress(
    ui: UI, fallback_msg: str, cmd: list[str], timeout: int = 180, output: list[str] | None = None
) -> bool:
    """Run *cmd* showing live progress. Returns True on success.

    *output*, when given, receives every line the child printed, so a caller can
    show why it failed after the spinner has hidden it.

    A watchdog timer kills the subprocess if it hasn't exited after *timeout*
    seconds (default 180).  This prevents the installer from hanging
    indefinitely when the child stalls (e.g. during the instruction sync).
    """
    try:
        proc = subprocess.Popen(
            cmd,
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
            text=True,
        )
    except FileNotFoundError:
        return False

    assert proc.stdout is not None  # noqa: S101  # trw:intentional Popen(stdout=PIPE) guarantees non-None .stdout

    killed_by_watchdog = False

    def _watchdog_kill() -> None:
        nonlocal killed_by_watchdog
        killed_by_watchdog = True
        proc.kill()

    watchdog = threading.Timer(timeout, _watchdog_kill)
    watchdog.daemon = True
    watchdog.start()

    try:
        if ui.interactive:
            ui.start_spinner(fallback_msg)
            file_count = 0
            for line in proc.stdout:
                line = line.strip()
                if output is not None:
                    output.append(line)
                # Phase markers update the status message (e.g., "Phase: Syncing instruction files...")
                if line.startswith("Phase:"):
                    phase_label = line.partition(":")[2].strip()
                    ui.update_spinner(f"{fallback_msg} ({file_count} files) {phase_label}")
                elif _WARNING_LINE_RE.match(line):
                    # A warning is the one child line the operator MUST still
                    # see after the spinner has scrolled away (e.g. an
                    # update-project refusal that left their AGENTS.md stale).
                    ui.defer_warn(_WARNING_LINE_RE.sub("", line, count=1).strip())
                elif _CONFIG_WARNING_LINE_RE.match(line):
                    ui.defer_warn(_CONFIG_WARNING_LINE_RE.sub("", line, count=1).strip())  # defer_warn dedups
                elif _RETIRED_LINE_RE.match(line):
                    ui.defer_warn(line)
                elif _PROGRESS_LINE_RE.match(line):
                    file_count += 1
                    short = _PROGRESS_LINE_RE.sub("", line, count=1)[:60]
                    ui.update_spinner(f"{fallback_msg} ({file_count} files) {DIM}{short}{NC}")
        else:
            for line in proc.stdout:
                if output is not None:
                    output.append(line.strip())
                if _WARNING_LINE_RE.match(line.strip()) and not ui.first_sighting(
                    _WARNING_LINE_RE.sub("", line.strip(), count=1)
                ):
                    continue  # the same notice every earlier per-client run already showed
                if _CONFIG_WARNING_LINE_RE.match(line.strip()) and not ui.first_sighting(
                    _CONFIG_WARNING_LINE_RE.sub("", line.strip(), count=1).strip()
                ):
                    continue  # the same config warning every earlier per-client run already showed
                if not ui.quiet:
                    print(f"{GREEN}[TRW]{NC}   {line.rstrip()}")

        proc.wait(timeout=10)
    except subprocess.TimeoutExpired:
        proc.kill()
        proc.wait()
    except BaseException:
        # Ctrl-C (KeyboardInterrupt) or SystemExit mid-stream: never orphan
        # the child — subprocess.run() reaps on interrupt, Popen does not.
        proc.kill()
        proc.wait()
        ui.stop_spinner(False, "", f"{fallback_msg} interrupted")
        raise
    finally:
        watchdog.cancel()

    if killed_by_watchdog:
        ui.defer_warn(f"{fallback_msg} timed out after {timeout}s")

    return proc.returncode == 0


# ── Config file update ───────────────────────────────────────────────


def write_platform_credentials(config_path: Path, api_key: str) -> Path | None:
    """Write *api_key* to ``.trw/credentials.yaml`` (mode 0600).

    PRD-SEC-005-FR01: the platform bearer credential is stored in an ignored,
    owner-only file sibling to ``config.yaml`` — never in the git-tracked
    config. The chmod is best-effort (Windows has no POSIX mode bits).

    Returns the credentials path on a successful write, or ``None`` when there
    is no key to write -- including when *api_key* IS the computer-wide sign-in
    (``~/.trw/credentials.yaml``): the project then resolves it from there at
    runtime, so a rotation replaces one copy instead of one per project.

    The file is created at 0600 from the first byte (a temp opened
    ``O_CREAT|O_EXCL|O_NOFOLLOW`` at 0600, then renamed over the target), never
    written world-readable and chmod-ed afterwards.
    """
    if not api_key or api_key == _read_machine_credentials_key():
        return None
    credentials_path = config_path.parent / "credentials.yaml"
    credentials_path.parent.mkdir(parents=True, exist_ok=True)
    body = f'# TRW platform credential — ignored by git, mode 0600 (PRD-SEC-005).\nplatform_api_key: "{api_key}"\n'
    tmp = credentials_path.with_name(f".credentials.yaml.{os.getpid()}.tmp")
    flags = os.O_WRONLY | os.O_CREAT | os.O_EXCL | getattr(os, "O_NOFOLLOW", 0)
    try:
        with os.fdopen(os.open(tmp, flags, 0o600), "w", encoding="utf-8") as handle:
            handle.write(body)
        os.replace(tmp, credentials_path)
    except BaseException:
        with contextlib.suppress(OSError):
            tmp.unlink()
        raise
    return credentials_path


def update_config(
    config_path: Path,
    project_name: str,
    api_key: str,
    telemetry_enabled: bool,
    *,
    target_platforms: list[str] | None = None,
    rewrite_platform_urls: bool = True,
) -> bool:
    """Update .trw/config.yaml with installation settings.

    ``embeddings_enabled`` is written by :func:`persist_embeddings_choice`.
    """
    if not config_path.is_file():
        return False

    lines = config_path.read_text(encoding="utf-8").splitlines(keepends=True)
    platform_url = "https://api.trwframework.com"
    effective_target_platforms = target_platforms or None

    updated: set[str] = set()
    out: list[str] = []
    replacing_platform_urls = False
    replacing_target_platforms = False

    for line in lines:
        normalized_line = line if line.endswith("\n") else line + "\n"
        s = normalized_line.lstrip()
        stripped = s.strip()

        if replacing_target_platforms:
            if not stripped or stripped.startswith(("#", "- ")):
                continue
            replacing_target_platforms = False

        if replacing_platform_urls:
            if not stripped or stripped.startswith(("#", "- ")):
                continue
            replacing_platform_urls = False

        if s.startswith("installation_id:"):
            out.append(f"installation_id: {project_name}\n")
            updated.add("installation_id")
            continue
        if s.startswith("platform_api_key:"):
            # PRD-SEC-005-FR01: the credential no longer lives in the
            # git-tracked config.yaml. Blank any existing field (a legacy
            # tracked key is migrated to credentials.yaml by the caller) and
            # never write the secret here for fresh installs.
            out.append('platform_api_key: ""\n')
            updated.add("platform_api_key")
            continue
        if s.startswith("platform_telemetry_enabled:"):
            val = "true" if telemetry_enabled else "false"
            out.append(f"platform_telemetry_enabled: {val}\n")
            updated.add("platform_telemetry_enabled")
            continue
        if s.startswith("target_platforms:") and effective_target_platforms is not None:
            out.append("target_platforms:\n")
            out.extend(f'  - "{ide}"\n' for ide in effective_target_platforms)
            updated.add("target_platforms")
            replacing_target_platforms = True
            continue
        if s.startswith("platform_urls:"):
            updated.add("platform_urls")
            if rewrite_platform_urls and (api_key or telemetry_enabled):
                out.append("platform_urls:\n")
                out.append(f'  - "{platform_url}"\n')
                updated.add("platform_urls_written")
                replacing_platform_urls = True
                continue
            out.append(normalized_line)
            continue

        # Skip commented-out platform config hints
        skip_prefixes = (
            "# platform_urls:",
            '#   - "https://api.',
            "# platform_api_key:",
            "# platform_telemetry_enabled:",
            "# Platform telemetry",
        )
        if any(s.startswith(p) for p in skip_prefixes):
            continue

        out.append(normalized_line)

    # Append missing keys
    if "installation_id" not in updated:
        out.append(f"installation_id: {project_name}\n")
    # PRD-SEC-005-FR01: never append the secret into the tracked config.yaml.
    # The key is persisted to .trw/credentials.yaml (0600) by the caller.
    # Recorded either way, so the next install reuses the answer instead of asking again (an OFF answer used to
    # leave no line, and every upgrade re-asked).
    if "platform_telemetry_enabled" not in updated:
        out.append(f"platform_telemetry_enabled: {'true' if telemetry_enabled else 'false'}\n")
    if rewrite_platform_urls and (api_key or telemetry_enabled) and "platform_urls_written" not in updated:
        out.append("platform_urls:\n")
        out.append(f'  - "{platform_url}"\n')
    if effective_target_platforms and "target_platforms" not in updated:
        out.append("target_platforms:\n")
        out.extend(f'  - "{ide}"\n' for ide in effective_target_platforms)

    config_path.write_text("".join(out), encoding="utf-8")
    return True


# ── Health check ─────────────────────────────────────────────────


def _check_backend_health(url: str, timeout: float = 5.0) -> dict[str, object]:
    """Probe a backend health endpoint. Returns status dict.

    Uses only stdlib — no external dependencies.
    """
    import urllib.error
    import urllib.request

    health_url = f"{url.rstrip('/')}/v1/health"
    try:
        req = urllib.request.Request(health_url, method="GET")
        with urllib.request.urlopen(req, timeout=timeout) as resp:
            data = json.loads(resp.read().decode("utf-8"))
            return {"url": url, "reachable": True, "status": data.get("status", "ok")}
    except urllib.error.HTTPError as exc:
        return {"url": url, "reachable": True, "status": f"http-{exc.code}"}
    except Exception:
        return {"url": url, "reachable": False, "status": "unreachable"}


def _check_all_backends(target_dir: Path) -> list[dict[str, object]]:
    """Check connectivity to all configured platform backends.

    Reads platform_urls from config.yaml (simple line parsing) and probes
    each one. Also checks localhost:8000 if a docker-compose.yml exists
    in the project (indicating a local backend may be running).
    """
    results: list[dict[str, object]] = []
    urls: list[str] = []

    # Read platform_urls from config.yaml
    config_path = target_dir / ".trw" / "config.yaml"
    if config_path.is_file():
        try:
            in_urls = False
            for line in config_path.read_text(encoding="utf-8").splitlines():
                stripped = line.strip()
                if stripped.startswith("platform_urls:"):
                    in_urls = True
                    continue
                if in_urls:
                    if stripped.startswith("- "):
                        url = stripped[2:].strip().strip('"').strip("'")
                        if url:
                            urls.append(url)
                    elif stripped and not stripped.startswith("#"):
                        in_urls = False
        except OSError:
            pass

    # Check for local Docker backend
    if (target_dir / "docker-compose.yml").is_file() or (target_dir / "docker-compose.yaml").is_file():
        local_url = "http://localhost:8000"
        if local_url not in urls:
            urls.insert(0, local_url)

    # Probe all backends in parallel for faster results
    if not urls:
        return results
    if len(urls) == 1:
        return [_check_backend_health(urls[0])]

    from concurrent.futures import ThreadPoolExecutor, as_completed
    from concurrent.futures import TimeoutError as _FuturesTimeout

    with ThreadPoolExecutor(max_workers=min(len(urls), 4)) as pool:
        futures = {pool.submit(_check_backend_health, url): url for url in urls}
        try:
            for future in as_completed(futures, timeout=10):
                try:
                    results.append(future.result())
                except Exception:
                    results.append({"url": futures[future], "reachable": False, "status": "error"})
        except _FuturesTimeout:
            # More queued probes than the 10s pool ceiling allows (each probe
            # is individually bounded at 5s, but only 4 run at once). Report
            # the stragglers as timeouts instead of crashing what is by now a
            # fully-successful install.
            for future, url in futures.items():
                if not future.done():
                    future.cancel()
                    results.append({"url": url, "reachable": False, "status": "timeout"})

    # Preserve original URL ordering
    url_order = {url: i for i, url in enumerate(urls)}
    results.sort(key=lambda r: url_order.get(str(r["url"]), 999))
    return results


# ── MCP server restart ───────────────────────────────────────────


def _restart_mcp_servers(target_dir: Path, ui: UI) -> None:
    """Prepare the MCP server(s) to pick up this install.

    trw-mcp is stdio-only, so there is no background server to stop: write a
    version sentinel so the server detects the upgrade on the next tool call
    and advises ``/mcp``, and warn when another ``trw-mcp`` shadows this install.
    """

    trw_dir = target_dir / ".trw"

    # Write version sentinel for stdio instances to detect upgrade.
    #
    # DRY + truthful (installer-client bug 2026-07-21): record the version that
    # the MCP client will ACTUALLY run — the PATH-resolved `trw-mcp` — NOT the
    # version this installer intended to install (TRW_VERSION). When a stale
    # install shadows PATH (e.g. an old `pip install --user` trw-mcp that a fresh
    # install did not supersede), stamping TRW_VERSION produces a marker that
    # lies about what runs: the runtime then sees marker > running and advises a
    # `/mcp` reload that CANNOT help, because a reload re-spawns the same stale
    # executable. Writing the resolved version keeps the marker honest and the
    # advisory correct, and we warn loudly at install time so the shadow is
    # visible instead of silently masked.
    #
    # I1/I2 (installer refinement 5.1.0): "intended" is what this run actually
    # DECIDED to leave resident — `_MCP_EFFECTIVE_VERSION` set by the downgrade
    # guard in phase_install_packages — not the blind bundle constant. A
    # `kept-installed` run intentionally keeps a newer trw-mcp than TRW_VERSION;
    # comparing against the raw bundle constant flagged that intentional keep as
    # a "stale shadow" and prescribed a destructive `pip uninstall` that would
    # remove the only real install.
    # None when the read-back failed: nothing unverified is stamped or compared.
    effective_version = _MCP_EFFECTIVE_VERSION
    sentinel_path = trw_dir / "installed-version.json"
    resolved_version = _resolve_path_trw_mcp_version()
    marker_version = resolved_version or effective_version
    fields = (("version", marker_version), ("intended", effective_version), ("timestamp", _iso_now()))
    try:
        sentinel_path.write_text(json.dumps({k: v for k, v in fields if v is not None}), encoding="utf-8")
    except OSError:  # trw-fail-silent-allow: best-effort sentinel write, install must never fail on it
        pass

    shadow = shutil.which("trw-mcp")
    identity = _same_file(shadow, _MCP_TARGET_BINARY) if shadow and _MCP_TARGET_BINARY else None
    # TRW's own ~/.local/bin launcher shim exec'ing this install is not a shadow.
    other_binary = identity is False and not _is_launcher_shim_to(str(shadow), str(_MCP_TARGET_BINARY))
    if (resolved_version and effective_version and resolved_version != effective_version) or other_binary:
        ui.step_warn(
            f"A trw-mcp {resolved_version or '(unknown version)'} is shadowing the intended "
            f"{effective_version or 'install'} on your PATH — the intended install will NOT run until this is fixed."
        )
        if shadow:
            ui.step_warn(f"  Shadowing binary: {_display_path(shadow)}")
        if other_binary:
            ui.step_warn(f"  Intended binary: {_display_path(_MCP_TARGET_BINARY or '')}")
        ui.step_warn(
            "  Fix: remove the stale install (e.g. 'pip uninstall trw-mcp' in the "
            "environment that owns it) or reorder PATH so the new install wins, then reconnect the MCP client."
        )
    elif shadow and identity is None:
        ui.step_warn(
            f"Could not verify that {shadow} (on your PATH) is the trw-mcp this installer installed "
            f"(intended: {_MCP_TARGET_BINARY or 'unresolved'}). Run 'which -a trw-mcp' to check."
        )

    _write_version_yaml_metadata(target_dir)


# PRD-INFRA-200 FR02: the one line of stdout the daemon-stop verdict is read from.
_DAEMON_STOP_LINE_PREFIX = "TRW_DAEMON_STOP="

# Run in the TARGET interpreter, so the version compared is the trw-memory this
# run installed (not TRW_VERSION, which is trw-mcp's) and the stop goes through
# trw-memory's own identity check (pid plus OS start, or for a 4.0 record the daemon's own
# socket, pid and ps entry: E2E-INC-134). argv[1] is the project; argv[2] is "1" to stop
# only a strictly OLDER daemon (the plain, non --upgrade path), and the project's grant is
# what the 4.0 socket proof presents.
_DAEMON_STOP_SOURCE = (
    "import json, sys\n"
    "from pathlib import Path\n"
    "from trw_memory import __version__\n"
    "from trw_memory.daemon import DaemonPaths, read_checkout_grant, stop_outdated_daemon\n"
    "from trw_memory.exceptions import DaemonAuthError\n"
    "from trw_mcp.server._doctor_launcher_divergence import reconnect_client_configs\n"
    "try:\n"
    "    token = read_checkout_grant(Path(sys.argv[1]))\n"
    "except DaemonAuthError:\n"
    "    token = None\n"
    "result = stop_outdated_daemon(\n"
    "    DaemonPaths.resolve(create=False), __version__, older_only=sys.argv[2] == '1', token=token)\n"
    "configs = reconnect_client_configs(Path(sys.argv[1]))\n"
    f"print({_DAEMON_STOP_LINE_PREFIX!r} + json.dumps("
    "{'outcome': result.outcome, 'detail': result.detail, 'configs': configs}))\n"
)


def _daemon_stop_verdict(
    python: str, target_dir: Path, env: dict[str, str], older_only: bool = False
) -> tuple[dict[str, object] | None, str]:
    """Run :data:`_DAEMON_STOP_SOURCE`; ``(verdict, "")``, or ``(None, why no verdict came back)``."""
    try:
        proc = subprocess.run(
            [python, "-B", "-c", _DAEMON_STOP_SOURCE, str(target_dir), "1" if older_only else "0"],
            env=env,
            capture_output=True,
            text=True,
            timeout=60,
        )
    except (OSError, subprocess.TimeoutExpired) as exc:  # trw-fail-silent-allow: the reason is returned and printed
        return None, f"{type(exc).__name__}: {exc}"
    for line in reversed(proc.stdout.splitlines()):
        if line.startswith(_DAEMON_STOP_LINE_PREFIX):
            try:
                verdict = json.loads(line[len(_DAEMON_STOP_LINE_PREFIX) :])
            except ValueError as exc:  # trw-fail-silent-allow: the reason is returned and printed
                return None, f"an unparseable verdict ({exc})"
            return (verdict, "") if isinstance(verdict, dict) else (None, "an unparseable verdict")
    stderr_tail = (proc.stderr or "").strip().splitlines()
    return None, stderr_tail[-1] if stderr_tail else f"exit code {proc.returncode}"


def stop_outdated_memory_daemon(
    python: str, target_dir: Path, ui: UI, pip_target: str = "", *, older_only: bool = False
) -> None:
    """``--upgrade``: stop a memory daemon serving another version, then name the clients to reconnect.

    *older_only* is the plain run over an EXISTING install (E2E-INC-134): it stops only a daemon strictly
    older than the installed trw-memory and says nothing when there is none, so a fresh install, or a
    same-version or newer daemon, is never touched.

    A client refuses only a major mismatch, so after a minor or patch upgrade the
    old daemon kept serving old code until someone killed it (PRD-INFRA-200 FR02).
    The environment is this process's own plus the ``--pip-target`` import path:
    the pip runtime env rewrites ``XDG_DATA_HOME``, which would move the user
    memory directory and miss the running daemon's record.
    """
    env = dict(os.environ)
    if pip_target:
        env["PYTHONPATH"] = pip_target + os.pathsep + env.get("PYTHONPATH", "")
    verdict, failure = _daemon_stop_verdict(python, target_dir, env, older_only)
    if older_only and (verdict is None or verdict.get("outcome") not in ("stopped", "unproven", "invalid")):
        return  # a plain run reports only a daemon it stopped or found older and could not stop
    configs: object = None
    if verdict is None:
        ui.step_warn(f"Could not check the trw-memory daemon ({failure}).")
        ui.step_warn("  If one runs an older version, stop it: its pid is in daemon.json in the TRW memory dir.")
    else:
        detail = verdict.get("detail", "")
        if verdict.get("outcome") == "stopped":
            ui.step_ok(f"Memory daemon {detail}; the next client call starts the new one")
        elif verdict.get("outcome") in ("unproven", "invalid"):
            ui.step_warn(f"The running memory daemon was not stopped: {detail}")
            # trw_memory's own remedy text is deliberately agent-safe (it never says
            # "kill <pid>", so an agent reading it cannot copy-execute it — HB-2,
            # DoD-5 run 2026-09-26). This installer prints for the human operator
            # running --upgrade directly, so it names the manual remedy explicitly
            # here (docs/sprint-next/UPGRADE-NOTES-8.0.0.md's "Stop the old memory
            # daemon" step): stop only the pid the detail itself names, never guess one.
            pid_match = re.search(r"\bpid (\d+)\b", detail)
            if pid_match:
                pid = pid_match.group(1)
                ui.step_warn(
                    f"  Stop it by hand: verify pid {pid} is python -m trw_memory.server, then run: kill {pid}"
                )
        configs = verdict.get("configs")
    # Every running stdio trw-mcp still runs the old code, whatever the daemon check found.
    named = configs if isinstance(configs, list) else []
    ui.step_warn(
        f"Reconnect every MCP client so it runs the upgraded trw-mcp (e.g. /mcp in Claude Code){':' if named else '.'}"
    )
    for rel in named:
        ui.step_warn(f"  reconnect the client configured by {rel}")


def _display_path(path: str) -> str:
    """*path* with ``..`` segments collapsed, for messages (a RECORD-derived path reads ``site-packages/../../../bin``)."""
    return os.path.normpath(os.path.abspath(path))


def _same_file(a: str, b: str) -> bool | None:
    """True when both paths name one file (symlinks resolved); ``None`` when unverifiable."""
    try:
        return os.path.samefile(a, b)
    except OSError:  # trw-fail-silent-allow: None is reported as an unverified identity warning
        return None


def _probe_mcp_binary(python: str) -> str | None:
    """Return the ``trw-mcp`` console script the *python* interpreter's trw-mcp installed.

    Read from the distribution's own RECORD, so a venv, ``--user`` and system
    install each report where pip actually put the script. Only RECORD proves
    ownership: ``None`` when it names no existing script or the probe fails, and
    the caller then reports the binary identity as "unverified".
    """
    code = (
        "import importlib.metadata as m, pathlib as p;"
        "n=('trw-mcp','trw-mcp.exe');"
        "c=[f.locate() for f in m.distribution('trw-mcp').files or () if f.name in n];"
        "print(next((str(f) for f in c if p.Path(f).is_file()),''))"
    )
    try:
        result = subprocess.run([python, "-B", "-c", code], capture_output=True, text=True, timeout=30, check=False)
    except (
        OSError,
        subprocess.SubprocessError,
    ):  # trw-fail-silent-allow: no binary identity -> version-only shadow check
        return None
    out = (getattr(result, "stdout", "") or "").strip()
    return out if getattr(result, "returncode", 1) == 0 and out and Path(out).is_file() else None


def _resolve_path_trw_mcp_version() -> str | None:
    """Return the version of the ``trw-mcp`` that PATH actually resolves.

    This is the binary an MCP client will spawn — which is NOT necessarily the
    one this installer just installed if a stale copy shadows PATH. Returns
    ``None`` when no ``trw-mcp`` is on PATH or its version cannot be read, in
    which case the caller falls back to the intended ``TRW_VERSION``.
    """
    exe = shutil.which("trw-mcp")
    if not exe:
        return None
    try:
        out = subprocess.run(
            [exe, "--version"],
            capture_output=True,
            text=True,
            timeout=10,
            check=False,
        ).stdout.strip()
    except (OSError, subprocess.TimeoutExpired):
        return None
    # "trw-mcp X.Y.Z" -> "X.Y.Z"; tolerate bare "X.Y.Z".
    parts = out.split()
    return parts[-1] if parts else None


def _merge_yaml_scalar(text: str, field: str, value: str) -> str:
    """Replace ``field:`` in ``text`` or append it, preserving every other key.

    Deliberately duplicated from ``trw_mcp.framework_integrity`` rather than
    imported: this installer is a single self-contained file that must run
    before (and independently of) any importable trw-mcp.
    """
    pattern = re.compile(rf"^{re.escape(field)}:.*$", re.MULTILINE)
    replacement = f"{field}: {value}"
    if pattern.search(text):
        return pattern.sub(replacement, text, count=1)
    suffix = "" if not text or text.endswith("\n") else "\n"
    return f"{text}{suffix}{replacement}\n"


def _write_version_yaml_metadata(target_dir: Path) -> None:
    """Best-effort VERSION.yaml refresh for upgrade-only installer runs.

    `init-project` / `update-project` already write this file through the
    installed package — including the `registry_digest` / `framework_digest` /
    `aaref_digest` fields that bind the deployed canon generation. The
    standalone installer must also refresh it when `--upgrade` skips project
    setup, otherwise `.trw/installed-version.json` and
    `.trw/frameworks/VERSION.yaml` drift apart.

    The refresh is a MERGE of the fields this installer is authoritative for,
    never a whole-file rewrite. Rewriting destroyed the digest fields the
    installed package had just written, so every fresh bundle install reported
    a deployment stamp with no `registry_digest` — `needs_upgrade` on a
    brand-new install, and a `framework_integrity` FAIL while the stamp was
    still receipt-bound (L-QhRy).

    PRD-INFRA-192 FR12: no longer takes an *installed_version* — this
    file no longer carries a package-version stamp. `.trw/managed-artifacts.yaml`
    `packages` is the one record of resolved package versions now, and it is
    written by init-project/update-project, not this best-effort refresh.
    """
    version_path = target_dir / ".trw" / "frameworks" / "VERSION.yaml"
    try:
        version_path.parent.mkdir(parents=True, exist_ok=True)
        # Fallbacks derive from the DEPLOYED framework bodies when possible —
        # a hardcoded fallback inevitably goes stale (it shipped "v25_TRW" /
        # "v2.0.0" long after v26/v3.x were current).
        framework_version = _deployed_doc_version(
            target_dir / ".trw" / "frameworks" / "FRAMEWORK.md",
            r"(v\d+(?:\.\d+)*_TRW)",
            None,
        )
        aaref_version = _deployed_doc_version(
            target_dir / ".trw" / "frameworks" / "AARE-F-FRAMEWORK.md",
            r"\*\*Version\*\*:\s*(\d+\.\d+\.\d+)",
            None,
            prefix="v",
        )
        if framework_version is None or aaref_version is None:
            return
        text = version_path.read_text(encoding="utf-8") if version_path.is_file() else ""
        # PRD-INFRA-192 FR12: trw_mcp_version/trw_memory_version are no
        # longer stamped here — `.trw/managed-artifacts.yaml` `packages` is the
        # one record of resolved versions now (version-status reads it back).
        # Strip any stale stamp an older installer left behind.
        for stale_field in ("trw_mcp_version", "trw_memory_version"):
            text = re.sub(rf"^{stale_field}:.*\n?", "", text, flags=re.MULTILINE)
        for field, value in (
            ("framework_version", framework_version),
            ("aaref_version", aaref_version),
            ("deployed_at", f"'{_iso_now()}'"),
        ):
            text = _merge_yaml_scalar(text, field, value)
        version_path.write_text(text, encoding="utf-8")
    except OSError:  # trw-fail-silent-allow: best-effort; the sentinel remains the runtime restart signal
        pass


def _deployed_doc_version(doc_path: Path, pattern: str, fallback: str | None, prefix: str = "") -> str | None:
    """Extract a version label from a deployed framework doc header (best-effort)."""
    try:
        if doc_path.is_file():
            head = doc_path.read_text(encoding="utf-8", errors="replace")[:2000]
            m = re.search(pattern, head)
            if m:
                return f"{prefix}{m.group(1)}"
    except OSError:
        pass
    return fallback


def _iso_now() -> str:
    """Return current UTC timestamp in ISO 8601 format."""
    from datetime import datetime, timezone

    return datetime.now(timezone.utc).isoformat()


def _resolve_framework_version() -> str:
    """Resolve the installed trw-mcp version, falling back to the build stamp.

    Prefers the freshly-installed package metadata; ``TRW_VERSION`` is the
    build-time placeholder substituted into the generated installer.
    """
    try:
        return importlib_metadata.version("trw-mcp")
    except Exception:  # justified: metadata lookup is best-effort, never block emit
        return TRW_VERSION


# ── PRD-INFRA-150: downgrade guard ───────────────────────────────────
# Default decision labels emitted on the install log surface (NFR03). Kept as
# module constants (no magic strings) so the wording is DRY across the guard,
# the log formatter, and the tests asserting them.
_GUARD_DECISION_KEPT = "kept-installed (newer)"
_GUARD_DECISION_UPGRADE = "installed-bundled (upgrade)"
_GUARD_DECISION_EQUAL = "installed-bundled (equal)"
_GUARD_DECISION_FRESH = "installed-bundled (fresh)"


_PEP440_LITE = re.compile(
    r"^v?(?P<release>\d+(?:\.\d+)*)"
    r"(?:[._-]?(?P<pre_l>a|alpha|b|beta|rc|c)(?P<pre_n>\d*))?"
    r"(?:[._-]?post(?P<post>\d*))?"
    r"(?:[._-]?dev(?P<dev>\d*))?$"
)
_PRE_ORDER = {"a": 0, "alpha": 0, "b": 1, "beta": 1, "rc": 2, "c": 2}


def _version_key_fallback(version: str) -> tuple[object, ...]:
    """PEP-440-lite sort key used when ``packaging`` is unavailable.

    Covers the shapes trw releases actually use — ``X.Y.Z`` plus optional
    ``aN``/``bN``/``rcN``, ``.postN``, ``.devN`` — with PEP 440 ordering
    (dev < pre < release < post) and trailing-zero equality (``1.0 ==
    1.0.0``). Raises ``ValueError`` on anything else so callers keep their
    existing fail-open policy.
    """
    m = _PEP440_LITE.match(version.strip().lower())
    if m is None:
        raise ValueError(f"unparsable version: {version!r}")
    release = [int(x) for x in m.group("release").split(".")]
    while len(release) > 1 and release[-1] == 0:
        release.pop()
    pre_l, pre_n = m.group("pre_l"), m.group("pre_n")
    post, dev = m.group("post"), m.group("dev")
    if pre_l:
        pre = (0, _PRE_ORDER[pre_l], int(pre_n or 0))
    elif dev is not None and post is None:
        # packaging's NegativeInfinity trick: 1.0.dev1 < 1.0a1 < 1.0
        pre = (-1, 0, 0)
    else:
        pre = (1, 0, 0)
    post_key = (1, int(post or 0)) if post is not None else (0, 0)
    dev_key = (0, int(dev or 0)) if dev is not None else (1, 0)
    return (tuple(release), pre, post_key, dev_key)


def _compare_versions(a: str, b: str) -> int:
    """Compare two versions with PEP 440 semantics (PRD-INFRA-150 FR04).

    Returns 1 if ``a > b``, -1 if ``a < b``, 0 if equal. Uses
    ``packaging.version.Version`` so ``0.55.10 > 0.55.9`` (NOT lexicographic).
    Raises ``ValueError`` (``InvalidVersion`` is a subclass) when either
    operand is unparsable — callers decide the fail-open policy.

    ``packaging`` is a third-party import that a bare system python3 often
    lacks. Losing it must NOT silently disable the downgrade guard (the
    callers' broad ``except`` would mislabel every decision as "fresh"), so
    a stdlib PEP-440-lite key takes over when the import fails.
    """
    try:
        from packaging.version import Version
    except ModuleNotFoundError:
        ka, kb = _version_key_fallback(a), _version_key_fallback(b)
        return (ka > kb) - (ka < kb)

    va, vb = Version(a), Version(b)
    if va > vb:
        return 1
    if va < vb:
        return -1
    return 0


def downgrade_guard_decision(installed: str | None, bundled: str) -> tuple[bool, str]:
    """Return ``(skip_force_install, decision_label)`` for one package (FR04).

    The label is one of the ``_GUARD_DECISION_*`` constants and feeds the single
    structured decision log line emitted per package (NFR03).
    """
    if installed is None:
        return False, _GUARD_DECISION_FRESH
    try:
        cmp = _compare_versions(installed, bundled)
    except Exception:  # justified: unparsable installed metadata -> treat as fresh
        return False, _GUARD_DECISION_FRESH
    if cmp > 0:
        return True, _GUARD_DECISION_KEPT
    if cmp == 0:
        return False, _GUARD_DECISION_EQUAL
    return False, _GUARD_DECISION_UPGRADE


def format_guard_log_line(package: str, installed: str | None, bundled: str, decision: str) -> str:
    """Format the single structured decision log line for *package* (NFR03)."""
    shown = installed if installed is not None else "(absent)"
    return f"{package} installed={shown} bundled={bundled} decision={decision}"


def _probe_installed_version(python: str, package: str, target: str | None = None) -> str | None:
    """Return the version of *package* installed in the *python* interpreter (or ``--pip-target`` dir).

    Probes the TARGET interpreter via ``importlib.metadata`` in a subprocess so
    it reflects what the install will actually mutate (not the installer's own
    environment). Returns None when the package is absent or the probe errors —
    the guard treats both as "not newer" and proceeds (NFR02 fail-open).
    """
    try:
        result = subprocess.run(
            [
                python,
                "-B",
                "-c",
                (
                    "import importlib.metadata as m, sys;"
                    f"sys.path[:0]=[{target!r}] if {target!r} else [];"
                    f"print(m.version({package!r}))"
                ),
            ],
            capture_output=True,
            text=True,
            timeout=30,
        )
    except (
        OSError,
        subprocess.SubprocessError,
    ):  # trw-fail-silent-allow: unknown version -> guard proceeds, stamp omitted
        return None
    if result.returncode != 0:
        return None
    version = (getattr(result, "stdout", "") or "").strip()
    return version or None


def _anonymize_installation_id(raw_id: str) -> str:
    """Double SHA-256 hash for non-reversible anonymization (PRD-SEC-004-FR08).

    Self-contained replica of ``trw_memory.security.pii.anonymize_installation_id``
    / ``trw_mcp.telemetry.anonymizer.anonymize_installation_id`` — two rounds of
    SHA-256, first 16 hex chars of the second digest. The installer ships without
    importing trw_mcp/trw_memory (it RUNS before they are installed), so the
    logic is duplicated here. Keep byte-identical to the library helper so the
    installer's install_complete event hashes to the same value the running MCP
    server later reports for the same project.
    """
    first = hashlib.sha256(raw_id.encode()).hexdigest()
    return hashlib.sha256(first.encode()).hexdigest()[:16]


def _build_install_complete_payload(
    *,
    installation_id: str,
    profile: str,
) -> dict[str, str]:
    """Build the PRD-INFRA-142 FR01 install_complete event payload.

    Field contract (taxonomy v1, §0 of the PRD): installation_id, os_platform,
    python_version, framework_version, profile, install_outcome.

    PRD-SEC-004-FR08: ``installation_id`` is HASHED (double-SHA256, truncated)
    before egress so the raw project-directory name never leaves the machine.
    The remaining fields are host platform facts (os, python, framework, profile)
    — no PII. This matches the consent copy: pseudonymous, enumerated fields.
    """
    import platform as _platform

    return {
        "event_type": "install_complete",
        "installation_id": _anonymize_installation_id(installation_id),
        "os_platform": _platform.system() or "unknown",
        "python_version": _platform.python_version(),
        "framework_version": _resolve_framework_version(),
        "profile": profile,
        "install_outcome": "success",
    }


def _post_telemetry_event(
    api_base: str,
    api_key: str,
    event: dict[str, str],
    *,
    timeout: float = 5.0,
) -> bool:
    """POST a single telemetry event to ``{api_base}/v1/telemetry``.

    Mirrors the trw-mcp telemetry sender contract: Bearer-auth, JSON body of
    ``{"events": [event]}``. Returns True on a 2xx. Fire-and-forget: any
    network error returns False rather than raising (PRD-INFRA-142 NFR02).
    """
    import urllib.error
    import urllib.request

    body = json.dumps({"events": [event]}).encode("utf-8")
    req = urllib.request.Request(
        f"{api_base.rstrip('/')}/v1/telemetry",
        data=body,
        headers={
            "Content-Type": "application/json",
            "Authorization": f"Bearer {api_key}",
        },
        method="POST",
    )
    try:
        with urllib.request.urlopen(req, timeout=timeout) as resp:
            return bool(200 <= resp.status < 300)
    except (urllib.error.URLError, TimeoutError, OSError):
        return False


def _emit_install_complete_event(
    target_dir: Path,
    *,
    api_base: str = API_BASE,
    post_fn: Any | None = None,
) -> bool:
    """Emit the PRD-INFRA-142 FR01 ``install_complete`` telemetry event.

    Reads the just-written ``.trw/config.yaml`` to resolve the installation
    identity, API key, and telemetry opt-out. The emit is gated (NFR01):
    it fires ONLY when an API key is configured AND telemetry is enabled. On
    any failure — missing config, opt-out, or network error — it returns False
    and never raises, so the installer always exits cleanly (NFR02).

    ``post_fn`` is an injection seam for tests: a callable
    ``(api_base, api_key, event) -> bool``. Defaults to the real HTTP poster.
    """
    try:
        prior = _load_prior_config(target_dir)
        api_key = str(prior.get("api_key") or "").strip()
        telemetry_enabled = bool(prior.get("telemetry"))
        installation_id = str(prior.get("project_name") or "").strip()
        # NFR01 opt-out gate: no key or telemetry disabled → suppress silently.
        if not api_key or not telemetry_enabled or not installation_id:
            return False

        platform_urls = prior.get("platform_urls")
        resolved_base = api_base
        if isinstance(platform_urls, list) and platform_urls:
            resolved_base = str(platform_urls[0])

        prior_targets = prior.get("target_platforms")
        profile = "unknown"
        if isinstance(prior_targets, list) and prior_targets:
            profile = str(prior_targets[0])

        event = _build_install_complete_payload(
            installation_id=installation_id,
            profile=profile,
        )
        poster = post_fn if post_fn is not None else _post_telemetry_event
        return bool(poster(resolved_base, api_key, event))
    except Exception:  # justified: fire-and-forget, install must not fail on emit
        return False


