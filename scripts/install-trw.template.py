def _open_tty() -> TextIO | None:
    """Open a TTY for reading, or None if unavailable.

    Uses /dev/tty on Unix and CON on Windows. Every prompt reads through here, so a live spinner is
    stopped first: its thread would otherwise repaint over the question.
    """
    _halt_live_spinners()
    for tty_path in () if _env_flag("TRW_HEADLESS") else ("/dev/tty", "CON"):  # headless: no prompt ever
        try:
            return open(tty_path, encoding="utf-8")
        except OSError:
            continue
    return None


def _has_controlling_tty() -> bool:
    """True when an interactive terminal is reachable for prompts.

    Every installer prompt (client selection, features, telemetry) reads from
    ``/dev/tty`` via :func:`_open_tty`, so they work even when ``sys.stdin`` is a
    pipe — which it ALWAYS is under ``curl … | bash`` (the standard install
    path). Interactivity must therefore be gated on the presence of a
    controlling terminal (a readable ``/dev/tty`` with a terminal ``stdout`` to
    render the prompt into), NOT on ``sys.stdin.isatty()`` alone — which is False
    under curl|bash and silently suppressed the client-selection prompt (an
    entire fresh install auto-configured detected clients without ever asking).
    """
    if not (hasattr(sys.stdout, "isatty") and sys.stdout.isatty()):
        return False
    tty = _open_tty()
    if tty is None:
        return False
    tty.close()
    return True


def prompt_yes_no(question: str, default: str = "n") -> bool:
    """Prompt for yes/no. Returns True for yes."""
    hint = "[Y/n]" if default == "y" else "[y/N]"
    tty = _open_tty()
    if tty is None:
        return default == "y"
    try:
        sys.stdout.write(f"    {question} {hint} ")
        sys.stdout.flush()
        answer = tty.readline().strip() or default
    finally:
        tty.close()
    return answer.lower().startswith("y")


def prompt_input(prompt_text: str, default: str = "") -> str:
    """Prompt for text input."""
    display = f"    {prompt_text}"
    if default:
        display += f" [{default}]"
    display += " "
    tty = _open_tty()
    if tty is None:
        return default
    try:
        sys.stdout.write(display)
        sys.stdout.flush()
        answer = tty.readline().strip() or default
    finally:
        tty.close()
    return answer


def _unique(values: list[str]) -> list[str]:
    """Return *values* with duplicates removed while preserving order."""
    return list(dict.fromkeys(values))


def _ide_label(ide: str) -> str:
    """Return a user-facing label for an installer IDE identifier."""
    return _IDE_META.get(ide, {}).get("label", ide)


def _format_ide_list(ides: list[str]) -> str:
    """Format IDE labels into a readable list."""
    labels = [_ide_label(ide) for ide in ides]
    if len(labels) <= 1:
        return labels[0] if labels else ""
    if len(labels) == 2:
        return f"{labels[0]} and {labels[1]}"
    return f"{', '.join(labels[:-1])}, and {labels[-1]}"


def _normalize_ide_targets(ides: list[str], *, strict: bool = True) -> list[str]:
    """Validate installer IDE identifiers and expand ``all``.

    In strict mode (CLI use), unknown identifiers raise ``ValueError`` with a
    "did you mean?" hint. In non-strict mode (loading prior config), unknown
    identifiers are dropped — we never want a stale config entry to crash the
    installer and block the user from upgrading.
    """
    import difflib

    normalized: list[str] = []
    dropped: list[str] = []
    for raw in ides:
        ide = raw.strip()
        if not ide:
            continue
        if ide == "all":
            return _SUPPORTED_IDES.copy()
        if ide in _SUPPORTED_IDES:
            normalized.append(ide)
        else:
            dropped.append(raw.strip())

    # Non-strict: silently drop unknowns; the caller decides whether to warn.
    if dropped and strict:
        supported = ", ".join([*_SUPPORTED_IDES, "all"])
        hints: list[str] = []
        for bad in dropped:
            matches = difflib.get_close_matches(bad, _SUPPORTED_IDES, n=1, cutoff=0.5)
            if matches:
                hints.append(f"'{bad}' (did you mean '{matches[0]}'?)")
            else:
                hints.append(f"'{bad}'")
        raise ValueError(f"Unknown --ide value(s): {', '.join(hints)}. Supported values: {supported}")
    return _unique(normalized)


def _parse_ide_argument(raw: str | None) -> list[str] | None:
    """Parse ``--ide`` into a normalized list of targets."""
    if raw is None:
        return None
    parts = [part.strip() for part in raw.split(",")]
    normalized = _normalize_ide_targets(parts)
    if not normalized:
        raise ValueError("--ide requires at least one client identifier")
    return normalized


def _read_single_key(tty: TextIO) -> str | None:
    """Read a single keypress from *tty* for checkbox navigation."""
    if os.name == "nt":
        try:
            import msvcrt

            getwch = getattr(msvcrt, "getwch")  # noqa: B009 -- Windows-only attribute; getattr keeps other platforms' type checkers quiet
            ch = str(getwch())
            if ch in ("\x00", "\xe0"):
                arrow = str(getwch())
                if arrow == "H":
                    return "UP"
                if arrow == "P":
                    return "DOWN"
                return arrow
            if ch in ("\r", "\n"):
                return "ENTER"
            if ch == " ":
                return "SPACE"
            return ch
        except (ImportError, OSError):
            return None

    try:
        import termios
        import tty as tty_mod
    except ImportError:
        return None

    try:
        fd = tty.fileno()
        old = termios.tcgetattr(fd)
    except (termios.error, OSError, ValueError):
        # /dev/tty opened but is not a real terminal (some sandboxes/CI);
        # mirror the Windows branch's resilience and let the caller fall
        # back to the numbered-selection prompt.
        return None
    try:
        tty_mod.setraw(fd)
        ch = tty.read(1)
        if ch == "\x1b":
            nxt = tty.read(1)
            if nxt == "[":
                arrow = tty.read(1)
                if arrow == "A":
                    return "UP"
                if arrow == "B":
                    return "DOWN"
                return arrow
            return ch
        if ch in ("\r", "\n"):
            return "ENTER"
        if ch == " ":
            return "SPACE"
        return ch
    finally:
        termios.tcsetattr(fd, termios.TCSADRAIN, old)


def _prompt_ide_selection_fallback(default_targets: list[str]) -> list[str] | None:
    """Fallback multi-select prompt for terminals without raw-key support."""
    default_display = ",".join(str(_SUPPORTED_IDES.index(ide) + 1) for ide in default_targets)
    print()
    print("Configure TRW for one or more clients:")
    for idx, ide in enumerate(_SUPPORTED_IDES, start=1):
        meta = _IDE_META[ide]
        marker = "[x]" if ide in default_targets else "[ ]"
        print(f"  {idx}. {marker} {meta['label']} — {meta['summary']}")
    print("  s. Skip project client setup for now")

    tty = _open_tty()
    if tty is None:
        return default_targets
    try:
        sys.stdout.write(f"\nSelection [default: {default_display}]: ")
        sys.stdout.flush()
        raw = tty.readline().strip().lower()
    finally:
        tty.close()

    if not raw:
        return default_targets
    if raw in {"s", "skip"}:
        return None

    choices: list[str] = []
    try:
        for part in raw.split(","):
            number = int(part.strip())
            if not (1 <= number <= len(_SUPPORTED_IDES)):
                raise ValueError
            choices.append(_SUPPORTED_IDES[number - 1])
    except ValueError:
        return default_targets
    return _normalize_ide_targets(choices)


