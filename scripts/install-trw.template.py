# Proprietary packages that ship a console-script entry point. Maps the
# distribution name -> (console-script name, ``module.callable`` target).
# Under a ``--target`` install (pip or uv) the backend-generated bin script
# does ``from <module> import main`` with NO PYTHONPATH setup, so it raises
# ModuleNotFoundError on a clean machine (or silently imports a different
# copy of the module if one happens to be on the default sys.path). We
# therefore re-write each as a PYTHONPATH wrapper mirroring the trw-mcp
# wrapper generated in phase_install_packages. trw-metaharness ships no console
# script, so it is intentionally absent.
PROPRIETARY_CONSOLE_SCRIPTS: tuple[tuple[str, str, str], ...] = (
    ("trw-distill", "trw-distill", "trw_distill.cli"),
    ("trw-loop", "trw-loop", "trw_loop.cli"),
    ("trw-swarm", "trw-swarm", "trw_swarm.cli"),
)


def _write_pythonpath_wrapper(
    bin_dir: Path,
    script_name: str,
    python: str,
    module_target: str,
    pythonpath_dir: str,
    ui: UI,
) -> Path:
    """Write ``<bin_dir>/<script_name>`` as a PYTHONPATH bash wrapper (FR04).

    Shared by phase_install_packages (``bin/trw-mcp``) and
    _write_proprietary_console_wrappers (proprietary CLIs): a ``--target``
    install has no importable site-packages on sys.path, so the console
    script must export PYTHONPATH before exec-ing the module's ``main()``.
    """
    wrapper = bin_dir / script_name
    wrapper.parent.mkdir(parents=True, exist_ok=True)
    wrapper.write_text(
        f"#!/bin/bash\n"
        f"export PYTHONPATH={pythonpath_dir}:$PYTHONPATH\n"
        f'exec {python} -B -c "from {module_target} import main; main()" "$@"\n'
    )
    wrapper.chmod(0o755)
    ui.info(f"PYTHONPATH wrapper: {wrapper} -> {pythonpath_dir}")
    return wrapper


def _write_proprietary_console_wrappers(python: str, target_dir: str, installed: list[str], ui: UI) -> list[Path]:
    """Re-write ``<target>/bin/<script>`` as PYTHONPATH wrappers.

    Only runs for ``--target`` installs (target_dir non-empty). For each
    proprietary package that (a) installed successfully and (b) ships a
    console script, replace the backend-generated bin script with a bash
    wrapper that exports ``PYTHONPATH=<target>`` before exec-ing the CLI —
    exactly the pattern phase_install_packages uses for ``bin/trw-mcp``.

    Without this, the bare ``trw-distill``/``trw-loop``/``trw-swarm`` commands
    that trw-mcp emits as remediation/regenerate hints fail to resolve the
    module in a target-dir layout. Returns the wrapper paths written (for
    observability + tests). Never raises through the caller.
    """
    if not target_dir:
        return []
    installed_names = {entry.split(" ", 1)[0] for entry in installed}
    bin_dir = Path(target_dir) / "bin"
    written: list[Path] = []
    for package, script_name, module_target in PROPRIETARY_CONSOLE_SCRIPTS:
        if package not in installed_names:
            continue
        written.append(_write_pythonpath_wrapper(bin_dir, script_name, python, module_target, target_dir, ui))
    return written


class CrossOriginRedirectError(RuntimeError):
    """A redirect pointed outside the origins the request was pinned to (PRD-SEC-021).

    Raised from the redirect handler BEFORE any request reaches the target.
    A RuntimeError, so every installer caller that downgrades on RuntimeError
    still does; never an OSError/URLError, so the retry loop does not treat it
    as a transient network failure. Carries only the target origin.
    """

    def __init__(self, target_origin: str) -> None:
        super().__init__(f"refused redirect to a different origin: {target_origin}")
        self.target_origin = target_origin


def _url_origin(url: str) -> tuple[str, str, int]:
    """Return *url*'s (scheme, host, port) origin; an unparseable port is -1 (never allowed)."""
    import urllib.parse

    parts = urllib.parse.urlsplit(url)
    scheme = parts.scheme.lower()
    try:
        port = parts.port if parts.port is not None else {"http": 80, "https": 443}.get(scheme, -1)
    except ValueError:
        port = -1
    return scheme, (parts.hostname or "").lower(), port


def _backend_redirect_origins(url: str) -> frozenset[tuple[str, str, int]]:
    """The origins a backend call to *url* may be redirected to: its own, plus the same-host https upgrade."""
    scheme, host, port = _url_origin(url)
    upgrade = {("https", host, 443)} if (scheme, port) == ("http", 80) else set()
    return frozenset({(scheme, host, port), *upgrade})


def _origin_pinned_opener(allowed_origins: frozenset[tuple[str, str, int]]) -> Any:
    """Build a urllib opener whose redirects may only land on *allowed_origins*.

    The installer's ONE outbound redirect policy (PRD-SEC-021): FR01 pins the
    backend license/entitlement calls to the backend's own origin; FR02's wheel
    download reuses this with the entitlement's allowed origins. Every hop is
    re-checked, and a refused hop raises CrossOriginRedirectError.
    """
    import urllib.parse
    import urllib.request

    def _refuse_unless_allowed(url: str, fp: Any) -> None:
        origin = _url_origin(url)
        if origin not in allowed_origins:
            if fp is not None:
                fp.close()
            raise CrossOriginRedirectError(f"{origin[0]}://{origin[1]}:{origin[2]}")

    class _OriginPinnedRedirectHandler(urllib.request.HTTPRedirectHandler):
        # Checked on entry too: urllib refuses an unsupported Location scheme
        # (file:, data:, ...) with an HTTPError 3xx the retry loop would retry.
        def http_error_302(self, req, fp, code, msg, headers):  # type: ignore[no-untyped-def]
            location = headers.get("location") or headers.get("uri")
            if location:
                _refuse_unless_allowed(urllib.parse.urljoin(req.full_url, location), fp)
            return super().http_error_302(req, fp, code, msg, headers)

        http_error_301 = http_error_303 = http_error_307 = http_error_308 = http_error_302

        def redirect_request(self, req, fp, code, msg, headers, newurl):  # type: ignore[no-untyped-def]
            _refuse_unless_allowed(newurl, fp)
            return super().redirect_request(req, fp, code, msg, headers, newurl)

    return urllib.request.build_opener(_OriginPinnedRedirectHandler())


def _call_backend_json_with_retry(
    req: Any,
    timeout: int,
    denied_label: str,
    failure_label: str,
) -> dict[str, Any]:
    """Call a backend endpoint with up-to-3 exponential-backoff retries (1/2/4s).

    Shared skeleton for the proprietary-license and entitlement calls:
    4xx = permanent denial (reason surfaced, NO retry); 5xx / network /
    decode errors retry; exhausted retries raise RuntimeError. Secrets never
    appear in raised messages (PRD-INFRA-129 NFR04). Callers validate the
    payload AFTER return — a malformed success response must raise without
    burning retries, exactly as both inlined originals behaved. Redirects stay
    on the backend's origin (PRD-SEC-021 FR01): a cross-origin hop raises
    CrossOriginRedirectError, which is permanent and never retried.
    """
    import urllib.error

    opener = _origin_pinned_opener(_backend_redirect_origins(req.full_url))
    delays = (1.0, 2.0, 4.0)
    last_err: Exception | None = None
    for attempt, delay in enumerate(delays):
        try:
            # S310 is waived for this module in pyproject: backend URL, redirects origin-pinned.
            with opener.open(req, timeout=timeout) as resp:
                return cast("dict[str, Any]", json.loads(resp.read().decode()))
        except urllib.error.HTTPError as exc:
            if 400 <= exc.code < 500:
                reason = f"http {exc.code}"
                try:
                    detail = json.loads(exc.read().decode())
                    reason = str(detail.get("error") or detail.get("reason") or reason)
                except (json.JSONDecodeError, OSError):
                    pass
                raise RuntimeError(f"{denied_label} ({exc.code}): {reason}") from None
            last_err = exc
        except (urllib.error.URLError, TimeoutError, OSError, json.JSONDecodeError) as exc:
            last_err = exc
        if attempt < len(delays) - 1:
            time.sleep(delay)
    raise RuntimeError(f"{failure_label} after retries: {type(last_err).__name__}")


def _fetch_proprietary_license(
    backend_url: str,
    platform_api_key: str,
    timeout: int = 10,
) -> str:
    """Auto-derive a proprietary license from the configured platform API key.

    PRD-INFRA-129 FR02. Calls GET /v1/me/proprietary-license with the
    platform_api_key in the Authorization header and returns the
    plaintext license_key. The returned value lives only in the caller's
    memory; do not persist it to disk (NFR01).
    """
    import urllib.request

    req = urllib.request.Request(
        f"{backend_url.rstrip('/')}/me/proprietary-license",
        headers={"Accept": "application/json"},
        method="GET",
    )
    # PRD-SEC-021 FR01: an unredirected header is never copied onto a redirect hop.
    req.add_unredirected_header("Authorization", f"Bearer {platform_api_key}")
    payload = _call_backend_json_with_retry(req, timeout, "auto-license denied", "auto-license network failure")
    license_key = payload.get("license_key")
    if not isinstance(license_key, str) or not license_key:
        raise RuntimeError("malformed auto-license response")
    return license_key


