def _resolve_proprietary_license(
    *,
    with_proprietary: bool,
    explicit_license_key: str,
    backend_url: str,
    prior_config: dict[str, object],
    ui: UI,
    target_dir: Path | None = None,
    inferred: bool = False,
) -> tuple[str, bool]:
    """Resolve the effective license key + with_proprietary flag.

    PRD-INFRA-130 FR03: factored out of main() so behaviour is testable
    without invoking the argparse + Path resolution machinery.

    Behavior:
    - ``with_proprietary=False`` or explicit license already supplied:
      pass through unchanged.
    - Auto-derive (with_proprietary + empty license + a resolvable platform
      key): exchange the platform key for a fresh proprietary:install-scoped
      license via the backend (the platform key is NEVER sent directly to the
      entitlement endpoint, PRD-INFRA-129 FR06); on RuntimeError
      (network/auth/scope), warn via ``ui`` and downgrade
      ``with_proprietary=False`` so the public install can still proceed
      (PRD-126 FR05 + PRD-129 NFR02).
    - Auto-derive requested but no resolvable platform key:
      raise ``ValueError`` carrying an actionable hint enumerating every
      consulted source (PRD-INFRA-129 FR05/FR06) — never a raw argparse dump.
      UNLESS *inferred* is set: then the proprietary path was not asked for by
      this invocation at all, it was read off a
      ``.trw/proprietary-installed.json`` the project carries (historically a
      git-TRACKED file). A teammate cloning that project with no credentials
      would otherwise have their whole PUBLIC install exit 2 on a precondition
      for packages they never requested, which is exactly what PRD-INFRA-126
      FR05 forbids. So the inferred path warns and downgrades to
      ``with_proprietary=False``; only an explicit ``--with-proprietary`` /
      ``TRW_WITH_PROPRIETARY=1`` still fails hard.

    PRD-INFRA-129 FR05: when *target_dir* is provided the platform key is
    resolved through ``_resolve_prior_api_key`` (env > credentials.yaml; the
    git-tracked config.yaml is never read for the secret) so the precondition
    consults the SAME locations the rest of the install flow uses. When
    *target_dir* is None the resolver falls back to the already-resolved
    ``prior_config['api_key']`` (NFR08 backward compat).
    """
    auto_derive = with_proprietary and not explicit_license_key
    if not auto_derive:
        return explicit_license_key, with_proprietary

    platform_api_key = ""
    if target_dir is not None:
        # FR05: resolve via the canonical SEC-005 precedence (env >
        # credentials.yaml). The git-tracked config.yaml is NEVER read for the
        # secret — the upgrade path's `trw-mcp update-project` has already
        # migrated any legacy tracked key into credentials.yaml.
        platform_api_key = _resolve_prior_api_key(target_dir)
    else:
        raw = prior_config.get("api_key", "") if prior_config else ""
        platform_api_key = raw.strip() if isinstance(raw, str) else ""

    if not platform_api_key:
        if inferred:
            ui.step_warn(_PROPRIETARY_INFERRED_SKIP_WARNING)
            return "", False
        raise ValueError(_PROPRIETARY_PRECONDITION_ERROR)
    try:
        return _fetch_proprietary_license(backend_url, platform_api_key), True
    except RuntimeError as exc:
        detail = str(exc)
        # Distinguish a permanent denial (plan/scope/key) from a transient
        # network blip so the operator knows whether re-running will help.
        if isinstance(exc, CrossOriginRedirectError):
            hint = (
                " The backend redirected the credentialed request to a different "
                "origin, which the installer never follows. Check the configured "
                "backend URL, then re-run."
            )
        elif "denied" in detail:
            hint = (
                " This is a permanent denial (org plan, key scope, or unknown "
                "key). A platform key auto-derives a proprietary:install-scoped "
                "license; a 403 wrong-scope means the derive step did not run or "
                "the org plan lacks entitlement. Check the key's scope and your "
                "plan's proprietary access, fix the cause, then re-run."
            )
        else:
            hint = " Re-run with --with-proprietary once the backend is reachable."
        ui.step_warn(f"Auto-license fetch failed: {detail}.{hint} Continuing with public install only.")
        return "", False


def _post_proprietary_entitlement(
    backend_url: str,
    license_key: str,
    package: str,
    version: str,
    timeout: int = 10,
) -> dict[str, Any]:
    """Call POST /proprietary/entitlement with up-to-3 retries on transient errors.

    Returns the decoded JSON response on success. Raises RuntimeError on
    permanent failure (4xx, malformed response, exhausted retries). License
    key never appears in raised messages (NFR04). ``allowed_origins`` (PRD-
    SEC-021 FR03) is intentionally NOT required here \u2014 its absence is a
    distinct, named failure raised later by ``_download_proprietary_wheel``
    (FR02 OQ-003), not conflated with this generic malformed-response check.
    """
    import urllib.request

    body = json.dumps({"license_key": license_key, "package": package, "version": version}).encode()
    req = urllib.request.Request(
        f"{backend_url.rstrip('/')}/proprietary/entitlement",
        data=body,
        headers={"Content-Type": "application/json"},
        method="POST",
    )
    payload = _call_backend_json_with_retry(req, timeout, "entitlement denied", "entitlement network failure")
    if not all(k in payload for k in ("url", "sha256", "version")):
        raise RuntimeError(f"malformed entitlement response: keys={sorted(payload)}")
    return payload


class MissingAllowedOriginsError(RuntimeError):
    """The entitlement response omitted ``allowed_origins`` entirely (PRD-SEC-021 FR02 OQ-003).

    Distinct from WheelOriginNotAllowedError: this means the backend predates
    FR03 (an old backend), not that a present-but-unlisted origin was
    supplied (a compromised/misconfigured backend). Both fail closed and
    refuse the download; the distinct class is what lets a caller's log line
    tell the two apart without guessing.
    """


class WheelOriginNotAllowedError(RuntimeError):
    """The presigned wheel URL failed the https+allowed-origin check (PRD-SEC-021 FR02).

    Raised before any connection is attempted: the initial URL fails the
    check, a later redirect hop does (enforced by the same
    _origin_pinned_opener FR01 introduced, re-checking every hop), or the
    entitlement's own allowed_origins list itself carries a non-https or
    malformed entry (round-1 review P1 \u2014 see _wheel_allowed_origins).
    """

    def __init__(self, target_origin: str) -> None:
        super().__init__(f"origin not in the allowed list: {target_origin}")
        self.target_origin = target_origin


def _wheel_allowed_origins(allowed_origins: list[object]) -> frozenset[tuple[str, str, int]]:
    """Convert the entitlement response's https origin strings to origin tuples.

    Reuses ``_url_origin`` (FR01) so the wheel download shares the exact same
    origin-comparison semantics as the license/entitlement redirect pinning \u2014
    one origin-equality definition for the whole installer (PRD-SEC-021 OQ-001).

    Fails CLOSED and loud on any entry that is not a bare https origin (round-1
    review P1): a non-https scheme, a missing host, or one carrying a
    path/query/fragment/userinfo is refused with WheelOriginNotAllowedError
    before any request \u2014 never silently dropped from the set. Admitting a
    non-https sibling entry for the same host (e.g. both "https://good" and
    "http://good" in the same list) would let an https download be redirected
    to plain http on that host, since _origin_pinned_opener only checks set
    membership, not scheme; a malformed entry is treated as a server
    misconfiguration to refuse, not a value to sanitize.

    Round-2 review: the entitlement payload is untyped JSON, so an entry can
    be anything JSON allows (``None``, a number, a list, a dict) \u2014 not just
    a wrong-shaped string. A non-string entry is refused the same way a
    malformed string is (WheelOriginNotAllowedError), rather than escaping
    this function as a bare TypeError/AttributeError from ``urlsplit``.
    """
    import urllib.parse

    origins: set[tuple[str, str, int]] = set()
    for entry in allowed_origins:
        if not isinstance(entry, str):
            raise WheelOriginNotAllowedError(f"malformed allowed_origins entry (not a string): {entry!r}")
        try:
            parts = urllib.parse.urlsplit(entry)
            scheme, host, port = _url_origin(entry)
        except ValueError:
            raise WheelOriginNotAllowedError(f"malformed allowed_origins entry: {entry!r}") from None
        malformed = (
            scheme != "https"
            or not host
            or port == -1
            or parts.path not in ("", "/")
            or parts.query
            or parts.fragment
            or parts.username is not None
            or parts.password is not None
        )
        if malformed:
            raise WheelOriginNotAllowedError(f"malformed allowed_origins entry: {entry!r}")
        origins.add((scheme, host, port))
    return frozenset(origins)


def _download_proprietary_wheel(
    url: str,
    expected_sha256: str,
    dest_dir: Path,
    allowed_origins: object | None,
) -> Path:
    """Stream-download URL to dest_dir, verify SHA-256, return wheel path.

    PRD-SEC-021 FR02: refuses before connecting if url is non-https or its
    origin is not in allowed_origins (the entitlement response's own list),
    and re-validates every redirect hop against the same set by reusing FR01's
    ONE redirect policy, ``_origin_pinned_opener`` (OQ-001) \u2014 no second
    redirect/origin policy is introduced here. ``allowed_origins is None``
    means the entitlement payload omitted the key entirely (a pre-FR03
    backend): that raises MissingAllowedOriginsError, never the same
    exception class as an empty/non-matching list (WheelOriginNotAllowedError)
    (OQ-003), so an operator's log can tell "old backend" apart from
    "compromised/misconfigured backend" without guessing.

    Round-2 review: the parameter type is intentionally ``object | None``, not
    ``list[str] | None`` \u2014 the entitlement payload is untyped JSON
    (``dict[str, Any]``), so a present-but-wrong-shaped ``allowed_origins``
    (a bare string, a number, a dict) is a real reachable input, not a typing
    fiction. Only ``None`` (the key was absent, or the decoder handed us
    JSON ``null``) is the "old backend" case (MissingAllowedOriginsError);
    any other non-list shape is a malformed PRESENT field and raises
    WheelOriginNotAllowedError \u2014 same disposition as a malformed entry
    inside an otherwise-valid list (_wheel_allowed_origins), before any
    request is attempted.
    """
    import urllib.parse

    if allowed_origins is None:
        raise MissingAllowedOriginsError("entitlement response predates the allowed-origins field")
    if not isinstance(allowed_origins, list):
        raise WheelOriginNotAllowedError(f"allowed_origins is not a list: {type(allowed_origins).__name__}")
    pinned = _wheel_allowed_origins(allowed_origins)
    scheme, host, port = _url_origin(url)
    if scheme != "https" or (scheme, host, port) not in pinned:
        raise WheelOriginNotAllowedError(f"{scheme}://{host}:{port}")

    parsed_path = urllib.parse.urlparse(url).path
    filename = Path(parsed_path).name or "proprietary.whl"
    if not filename.endswith(".whl"):
        filename = filename + ".whl"
    dest = dest_dir / filename
    h = hashlib.sha256()
    opener = _origin_pinned_opener(pinned)
    try:
        # S310 is waived for this module in pyproject: presigned URL, origin-pinned.
        with opener.open(url, timeout=60) as resp, dest.open("wb") as f:
            for chunk in iter(lambda: resp.read(65536), b""):
                h.update(chunk)
                f.write(chunk)
    except Exception:
        dest.unlink(missing_ok=True)
        raise
    actual = h.hexdigest()
    if actual != expected_sha256:
        dest.unlink(missing_ok=True)
        raise RuntimeError(
            "proprietary_wheel_integrity_failure: "
            f"sha256 mismatch (expected {expected_sha256[:16]}..., got {actual[:16]}...)"
        )
    return dest


def _install_proprietary_wheel(
    python: str,
    wheel_path: Path,
    package: str,
    target_dir: str,
    ui: UI,
    log_root: Path | None = None,
) -> bool:
    """Install one proprietary wheel using the L-82faa67c rmtree pattern.

    Removes any pre-existing copy of the package from target_dir before
    reinstalling to prevent the silent PyPI downgrade documented in
    L-82faa67c. The wheel itself installs with ``--no-index --no-deps``, and
    only its PUBLIC requirements then resolve from the index (L-6f488d41), so
    a proprietary name never falls through to PyPI, where anyone could
    register it (PROPRIETARY-PIPELINE-ROT). The caller checks that every
    proprietary requirement was downloaded (_missing_proprietary_requirements).
    Routes through the resolved install backend so a uv-managed Python (no
    pip) works too.
    """
    pkg_module = package.replace("-", "_")
    if target_dir:
        target_root = Path(target_dir)
        for stale in target_root.glob(f"{pkg_module}*"):
            if stale.is_dir():
                shutil.rmtree(stale, ignore_errors=True)
            elif stale.is_file():
                stale.unlink(missing_ok=True)
    common = {"target_dir": target_dir, "no_warn_script_location": True, "upgrade": False, "quiet": False}
    cmds = [build_install_cmd(python, ui, [str(wheel_path)], no_index=True, no_deps=True, **common)]
    public = [req for name, req in _wheel_requirements(wheel_path) if name not in PROPRIETARY_PACKAGES_TUPLE]
    if public:
        cmds.append(build_install_cmd(python, ui, public, **common))
    return all(_run_proprietary_pip(cmd, package, target_dir, ui, log_root) for cmd in cmds)


_EXTRA_TEST = re.compile(r"""^extra ?== ?["'][^"']+["']$""")
_DIRECT_REFERENCE = re.compile(r"^\s*[A-Za-z0-9][A-Za-z0-9._-]*\s*(?:\[[^\]]*\]\s*)?@")
_MARKER_SEPARATOR = re.compile(r"\s;")


def _split_requirement(text: str) -> tuple[str, str]:
    """``(requirement, marker)`` of a ``Requires-Dist`` line.

    A direct reference (``name @ url``) ends its URL at whitespace (PEP 508), so a ``;`` inside the URL is not a marker
    separator; every other requirement splits at the first ``;``.
    """
    if _DIRECT_REFERENCE.match(text):
        parts = _MARKER_SEPARATOR.split(text, maxsplit=1)
        return parts[0], parts[1] if len(parts) > 1 else ""
    head, _, marker = text.partition(";")
    return head, marker


def _marker_is_active(marker: str) -> bool:
    """Whether a requirement stays in play when no extras are selected (PROPRIETARY-MARKER-EVAL).

    It is dropped only when every ``or`` alternative of the marker holds a plain ``extra == "name"`` test (a non-empty
    name), which is false with no extras. Nothing else ever drops one: a platform, Python-version or unreadable
    condition, a parenthesised marker, a quoted string that holds spaces, or a marker this reads wrongly all leave the
    requirement active, so a private requirement is never silently dropped (a wrong guess refuses the install, it does
    not skip the check). Stdlib only, no marker parser (nothing recurses on hostile metadata), and one linear pass over
    whitespace-separated tokens (no regex scan that can go quadratic on long runs of spaces).
    """
    words = marker.split()
    if not words or "(" in marker or ")" in marker:
        return True
    if any(word.count('"') + word.count("'") not in (0, 2) for word in words):
        return True  # a quoted string spans tokens: its content could pose as an operator
    alternatives: list[list[str]] = [[]]
    for word in words:
        if word == "or":
            alternatives.append([])
        else:
            alternatives[-1].append(word)
    for alternative in alternatives:
        atoms: list[list[str]] = [[]]
        for word in alternative:
            if word == "and":
                atoms.append([])
            else:
                atoms[-1].append(word)
        if any(not atom for atom in atoms):
            return True  # a dangling "and"/"or" is a malformed marker: not judged
        if not any(_EXTRA_TEST.match(" ".join(atom)) for atom in atoms):
            return True
    return False


def _wheel_requirements(wheel_path: Path) -> list[tuple[str, str]]:
    """``(normalized name, requirement text)`` for each ``Requires-Dist`` of *wheel_path* that is active with no extras.

    A requirement is dropped only when every alternative of its marker needs an extra (``_marker_is_active``).
    Stdlib only (the installer may run before ``packaging`` exists); pip evaluates any remaining marker.
    """
    try:
        with zipfile.ZipFile(wheel_path) as wheel:
            metadata_name = next(name for name in wheel.namelist() if name.endswith(".dist-info/METADATA"))
            metadata = BytesParser().parsebytes(wheel.read(metadata_name))
    except (
        OSError,
        StopIteration,
        zipfile.BadZipFile,
        KeyError,
    ):  # trw-fail-silent-allow: the --no-index pip install of this same wheel fails loudly
        return []
    requirements = []
    for text in metadata.get_all("Requires-Dist", []):
        match = re.match(r"\s*([A-Za-z0-9][A-Za-z0-9._-]*)", text)
        if match and _marker_is_active(_split_requirement(text)[1]):
            requirements.append((re.sub(r"[-_.]+", "-", match.group(1)).lower(), text.strip()))
    return requirements


_REQ_SPEC = re.compile(r"^\s*[A-Za-z0-9][A-Za-z0-9._-]*\s*(?:\[[^\]]*\]\s*)?(?P<rest>.*)$", re.DOTALL)
_SPEC_CLAUSE = re.compile(r"^\s*(===|==|!=|~=|>=|<=|>|<)\s*([A-Za-z0-9.*+!_-]+)\s*$")
_RELEASE_ONLY = re.compile(r"^\d{1,9}(?:\.\d{1,9}){0,15}$")
_LOCAL_LABEL = re.compile(r"^[a-z0-9]+(?:[._-][a-z0-9]+)*$")


def _parts(version: str) -> re.Match[str] | None:
    return _PEP440_LITE.match(version.strip().lower()) if len(version) <= 100 else None


def _release(version: str) -> tuple[int, ...] | None:
    """The numeric release segment of a plain ``X.Y.Z[suffix]`` version, or ``None`` if it is not one."""
    match = _parts(version)
    if match is None or not _RELEASE_ONLY.match(match.group("release")):
        return None
    return tuple(int(part) for part in match.group("release").split("."))


def _trim_zeros(release: tuple[int, ...]) -> tuple[int, ...]:
    """A release segment without trailing zeros, so ``1.0`` and ``1`` compare equal."""
    parts = list(release)
    while len(parts) > 1 and parts[-1] == 0:
        parts.pop()
    return tuple(parts)


def _is_pre(version: str) -> bool:
    match = _parts(version)
    return bool(match and (match.group("pre_l") or match.group("dev") is not None))


def _is_post(version: str) -> bool:
    match = _parts(version)
    return bool(match and match.group("post") is not None)


def _clause_holds(op: str, bound: str, version: str) -> bool | None:
    """One PEP 440 clause against *version*; ``None`` when it cannot be judged (callers fail closed).

    A well-formed local version label (``+g123``) is ignored; a malformed one, a local label in the bound, an epoch, a
    component over nine digits or a wildcard prefix that is not release-only is refused. ``<V`` excludes V's own
    pre-releases and ``>V`` its post-releases (PEP 440) unless V is itself one.
    """
    base, plus, local = version.partition("+")
    if (plus and not _LOCAL_LABEL.match(local.lower())) or "+" in bound:
        return None
    wildcard = bound.endswith(".*")
    have, want = _release(base), _release(bound[:-2] if wildcard else bound)
    if have is None or want is None:
        return None
    if wildcard:
        if op not in ("==", "!=") or not _RELEASE_ONLY.match(bound[:-2]):
            return None
        matches = have[: len(want)] == want
        return matches if op == "==" else not matches
    try:
        cmp = _compare_versions(base, bound)
        if op == "~=":
            parts = bound.split(".")
            if len(parts) < 2:
                return None
            upper = ".".join([*parts[:-2], str(int(parts[-2]) + 1)])
            return cmp >= 0 and _compare_versions(base, upper) < 0
    except (
        ValueError
    ):  # trw-fail-silent-allow: an unparsable version is "cannot judge", which the caller treats as unsatisfied
        return None
    if _trim_zeros(have) == _trim_zeros(want):
        if op == "<" and cmp < 0 and _is_pre(base) and not _is_pre(bound):
            return False
        if op == ">" and cmp > 0 and _is_post(base) and not _is_post(bound):
            return False
    return {
        "==": cmp == 0,
        "===": cmp == 0,
        "!=": cmp != 0,
        ">=": cmp >= 0,
        "<=": cmp <= 0,
        ">": cmp > 0,
        "<": cmp < 0,
    }[op]


def _requirement_spec(requirement: str) -> str:
    """The version specifier text of a ``Requires-Dist`` line (``>=0.1,<1``), ``@ url`` for a direct reference, or ``""``."""
    head = _split_requirement(requirement)[0]
    rest = _REQ_SPEC.match(head)
    return (rest.group("rest") if rest else "").strip().strip("()")


def _requirement_satisfied_by(requirement: str, version: str) -> bool:
    """Whether *version* satisfies the specifier of a ``Requires-Dist`` line (PROPRIETARY-PRIVATE-VERSION-CHECK).

    A direct reference (``name @ url``) or a clause that cannot be judged is NOT satisfied: a private requirement
    the installer cannot verify must never pass on its name alone. No specifier means any version satisfies it.
    """
    spec = _requirement_spec(requirement)
    if not spec:
        return True
    if spec.startswith("@"):
        return False
    for clause in spec.split(","):
        parsed = _SPEC_CLAUSE.match(clause)
        if parsed is None or _clause_holds(parsed.group(1), parsed.group(2), version) is not True:
            return False
    return True


def _missing_proprietary_requirements(wheel_path: Path, available: Mapping[str, str] | set[str]) -> list[str]:
    """Proprietary requirements of *wheel_path* that *available* (downloaded or already current) does not satisfy.

    *available* maps a package name to its version; a plain set of names (no versions known) is checked by name only.
    A package that is present at a version outside the requirement's specifier is reported as
    ``name<spec> (have X)`` so the refusal names what was wrong, not just that something was.
    """
    versions: Mapping[str, str | None] = available if isinstance(available, Mapping) else dict.fromkeys(available)
    unmet: list[str] = []
    for name, text in _wheel_requirements(wheel_path):
        if name not in PROPRIETARY_PACKAGES_TUPLE:
            continue
        if name not in versions:
            unmet.append(name)
            continue
        have = versions[name]
        if have is not None and not _requirement_satisfied_by(text, have):
            unmet.append(f"{name}{_requirement_spec(text)} (have {have})")
    return unmet


def _run_proprietary_pip(cmd: list[str], package: str, target_dir: str, ui: UI, log_root: Path | None) -> bool:
    # PRD-INFRA-129 FR04: capture stderr (instead of routing to DEVNULL via
    # _run_quiet) so a non-zero exit leaves a self-service diagnostic trail.
    # The success path stays quiet (no warn, no log) — only failures surface.
    try:
        env = _build_pip_runtime_env(_pip_target_from_cmd(cmd))
        result = subprocess.run(
            cmd,
            env=env,
            stdout=subprocess.DEVNULL,
            stderr=subprocess.PIPE,
            text=True,
            timeout=PROPRIETARY_PIP_INSTALL_TIMEOUT_SECONDS,
        )
    except (FileNotFoundError, subprocess.TimeoutExpired) as exc:
        _surface_proprietary_pip_failure(package, str(exc), target_dir, ui, log_root=log_root)
        return False  # trw-fail-silent-allow: surfaced above (console tail + per-package log); moved from _install_proprietary_wheel
    if result.returncode == 0:
        return True
    _surface_proprietary_pip_failure(package, result.stderr or "", target_dir, ui, log_root=log_root)
    return False


def _surface_proprietary_pip_failure(
    package: str, stderr: str, target_dir: str, ui: UI, log_root: Path | None = None
) -> None:
    """PRD-INFRA-129 FR04: warn with a stderr tail + write the full log.

    Emits a ``ui.warn`` carrying up to ``PROPRIETARY_PIP_STDERR_TAIL_CHARS`` of
    the captured stderr and writes the FULL stderr to
    ``<target_dir>/.trw/logs/install-pip-fail-<package>.log`` so an operator can
    diagnose a packaging break without reverse-engineering the installer
    (NFR06). The proprietary pip commands install a local wheel (``--no-index``)
    or its public requirements and never receive a license/API key in argv, so the captured
    stderr carries no plaintext secret (NFR07).
    """
    # Prefer the PROJECT root (log_root) — the pip --target dir / cwd
    # fallbacks predate project_dir threading and split records across trees.
    logs_root = log_root or (Path(target_dir) if target_dir else Path.cwd())
    log_path = logs_root / ".trw" / "logs" / f"install-pip-fail-{package}.log"
    log_written = ""
    try:
        log_path.parent.mkdir(parents=True, exist_ok=True)
        log_path.write_text(stderr, encoding="utf-8")
        log_written = str(log_path)
    except OSError:
        log_written = ""
    tail = stderr[-PROPRIETARY_PIP_STDERR_TAIL_CHARS:] if stderr else ""
    where = f" — full log: {log_written}" if log_written else ""
    ui.warn(
        f"pip install failed for {package}{where}\n"
        f"  pip stderr (last {PROPRIETARY_PIP_STDERR_TAIL_CHARS} chars):\n{tail}"
    )


def phase_install_proprietary(
    ui: UI,
    step: int,
    total: int,
    python: str,
    license_key: str,
    pins: dict[str, str],
    backend_url: str,
    target_dir: str = "",
    auto_confirm: bool = False,
    project_dir: Path | None = None,
) -> list[str]:
    """Install proprietary packages. Returns list of `<pkg> <version>` strings
    for packages that installed successfully.

    ``target_dir`` is the pip ``--target`` directory (usually empty);
    ``project_dir`` is the resolved project root — the ``.trw/`` tree where
    the completion event and failure logs belong. Without it, both fall back
    to cwd, which splits an install's records across two ``.trw/`` trees
    whenever the installer runs from outside the project.

    Per PRD-INFRA-126 FR05, failure of any per-package step does NOT roll
    back the public install \u2014 the function logs the failure, counts it,
    and continues. The phase prompt runs even if .trw/ already exists
    (mitigates L-43de9ce3 where the bash bootstrap pre-creates .trw/).
    """
    ui.step_header(step, total, "Installing proprietary packages")
    # FR02 \u2014 confirmation prompt. License key never echoed.
    if not auto_confirm:
        ui.info("Proprietary install will fetch from:")
        ui.info(f"  {backend_url}/proprietary/entitlement")
        for pkg in PROPRIETARY_PACKAGES_TUPLE:
            requested = pins.get(pkg, "latest")
            ui.info(f"  - {pkg} ({requested})")
        if not prompt_yes_no("Continue with proprietary install?", default="y"):
            ui.step_warn("Proprietary install skipped by user")
            return []
    installed: list[str] = []
    # PRD-INFRA-130 FR04: track per-package metadata for the structured event
    # written to ``.trw/install-events.jsonl`` on completion. Failures are
    # collected so observability captures partial-failure installs faithfully.
    installed_meta: list[dict[str, str]] = []
    failed_packages: list[str] = []
    tmpdir = Path(tempfile.mkdtemp(prefix="trw-proprietary-"))
    # Two-pass: download every wheel first so pass 2 can refuse a wheel whose
    # proprietary requirement (e.g. trw-distill -> trw-llm) was not fetched,
    # instead of letting it resolve from a public index.
    downloaded: list[tuple[str, Path, str, str]] = []  # (package, wheel_path, resolved_version, sha256)
    # PRD-INFRA-126 NFR05 idempotency: the marker records what a prior run
    # installed, so a re-run can skip a package the entitlement resolves to the
    # SAME version for. The interpreter probe is the second half of the test on
    # purpose \u2014 a marker alone would skip a package the user has since removed
    # (or that lives in a --target dir this interpreter cannot see), and the
    # probe failing open to None means "not proven current", so we install.
    entitled_marker = read_proprietary_marker(project_dir) if project_dir is not None else {}
    try:
        # Pass 1 \u2014 fetch all
        for package in PROPRIETARY_PACKAGES_TUPLE:
            version = pins.get(package, "latest")
            try:
                ui.start_spinner(f"Requesting entitlement for {package}...")
                payload = _post_proprietary_entitlement(backend_url, license_key, package, version)
                resolved_version = payload["version"]
                wheel_sha256 = payload["sha256"]
                ui.stop_spinner(
                    True,
                    f"Entitlement issued: {package} {resolved_version}",
                )
                if (
                    entitled_marker.get(package) == resolved_version
                    and _probe_installed_version(python, package) == resolved_version
                ):
                    ui.step_ok(f"{package} {resolved_version} already installed \u2014 skipped")
                    installed.append(f"{package} {resolved_version}")
                    continue
                ui.start_spinner(f"Downloading {package} {resolved_version}...")
                # PRD-SEC-021 FR02: pass the entitlement's own allowed_origins
                # (None if the key is absent — a pre-FR03 backend) so the
                # download refuses an unvalidated destination distinguishably.
                wheel = _download_proprietary_wheel(
                    payload["url"], wheel_sha256, tmpdir, payload.get("allowed_origins")
                )
                ui.stop_spinner(True, f"Downloaded {wheel.name} (sha verified)")
                downloaded.append((package, wheel, resolved_version, wheel_sha256))
            except RuntimeError as exc:
                # FR05 \u2014 log and continue; do NOT roll back the public install.
                ui.step_warn(f"proprietary_install_partial_failure: {package}: {exc}")
                failed_packages.append(package)

        # Pass 2 \u2014 install every fetched wheel, in tuple order (dependencies
        # first). A wheel whose proprietary requirement is neither already current
        # nor installed earlier in this pass is refused: it must never resolve from
        # a public index, and a prerequisite that failed to install is not available.
        available = {name: version for name, _, version in (entry.partition(" ") for entry in installed)}
        for package, wheel, resolved_version, wheel_sha256 in downloaded:
            missing = _missing_proprietary_requirements(wheel, available)
            if missing:
                ui.step_warn(
                    f"proprietary_install_partial_failure: {package}: requires {', '.join(missing)}, "
                    "which this install could not fetch, install or verify (never resolved from a public index)"
                )
                failed_packages.append(package)
                continue
            try:
                ui.start_spinner(f"Installing {package}...")
                if _install_proprietary_wheel(python, wheel, package, target_dir, ui, log_root=project_dir):
                    available[package] = resolved_version
                    ui.stop_spinner(True, f"Installed {package} {resolved_version}")
                    installed.append(f"{package} {resolved_version}")
                    installed_meta.append(
                        {
                            "name": package,
                            "version": resolved_version,
                            "sha256": wheel_sha256,
                        }
                    )
                else:
                    ui.stop_spinner(False, "", f"pip install failed for {package}")
                    failed_packages.append(package)
            except RuntimeError as exc:
                ui.step_warn(f"proprietary_install_partial_failure: {package}: {exc}")
                failed_packages.append(package)
    finally:
        shutil.rmtree(tmpdir, ignore_errors=True)
    # PRD-INFRA-130 FR04: emit one structured event per phase invocation,
    # rooted at the PROJECT directory when known (never the pip --target dir).
    events_root = project_dir or (Path(target_dir) if target_dir else Path.cwd())
    _emit_install_completed_event(events_root, installed_meta, failed_packages)
    if failed_packages:
        # Truthfulness: recap partial failure on the step surface (stderr in
        # script/quiet modes) — mid-stream warnings alone are easy to miss.
        # Exit stays 0 by design: proprietary failure never rolls back the
        # public install (PRD-INFRA-126 FR05).
        ui.step_fail(
            f"Proprietary: {len(installed)}/{len(installed) + len(failed_packages)} "
            f"packages installed — failed: {', '.join(failed_packages)} "
            "(public install unaffected; logs in .trw/logs/)"
        )
    # Re-write target-dir console scripts as PYTHONPATH wrappers so the bare
    # license-gated proprietary package commands resolve their module under
    # --target (mirrors the bin/trw-mcp wrapper). No-op for non-target installs.
    _write_proprietary_console_wrappers(python, target_dir, installed, ui)
    _print_distill_repo_intel_hint(ui, installed, python=python, target=target_dir)
    return installed


#: (importable module, pip requirement) for the extras that give trw-distill full map fidelity.
_DISTILL_MAP_EXTRAS: tuple[tuple[str, str], ...] = (
    ("tree_sitter", "tree-sitter>=0.24"),
    ("tree_sitter_python", "tree-sitter-python>=0.21"),
    ("tree_sitter_typescript", "tree-sitter-typescript>=0.21"),
    ("jedi", "jedi>=0.19"),
)


def _probe_missing_modules(python: str, modules: list[str], target: str) -> list[str] | None:
    """The *modules* the *python* interpreter (plus the ``--pip-target`` dir) cannot import, or None when unknown.

    Imports rather than only locating each module, so a wheel that is present but broken for this
    interpreter counts as missing. None means the probe itself could not run.
    """
    code = (
        "import importlib, sys\n"
        "target = sys.argv[1]\n"
        "if target:\n"
        "    sys.path.insert(0, target)\n"
        "for name in sys.argv[2:]:\n"
        "    try:\n"
        "        importlib.import_module(name)\n"
        "    except Exception:\n"
        "        print(name)\n"
    )
    try:
        result = subprocess.run(  # trw:intentional fixed argv; python is the interpreter the install used
            [python, "-B", "-c", code, target, *modules], capture_output=True, text=True, timeout=60, check=False
        )
    except (OSError, subprocess.SubprocessError):  # trw-fail-silent-allow: unknown -> the caller advises everything
        return None
    if result.returncode != 0:
        return None
    return [line.strip() for line in result.stdout.splitlines() if line.strip()]


def _missing_distill_map_extras(python: str, target: str) -> tuple[list[str], bool]:
    """``(pip requirements this interpreter cannot import, whether that was measured)``.

    When the probe cannot run every requirement is returned with ``False``: not knowing is not the same
    as present, and the caller must not report a guess as a finding.
    """
    missing = _probe_missing_modules(python, [module for module, _req in _DISTILL_MAP_EXTRAS], target)
    if missing is None:
        return [requirement for _module, requirement in _DISTILL_MAP_EXTRAS], False
    return [requirement for module, requirement in _DISTILL_MAP_EXTRAS if module in missing], True


def _print_distill_repo_intel_hint(ui: UI, installed: list[str], python: str = "", target: str = "") -> None:
    """Print a short next-steps hint when trw-distill installed successfully.

    trw-distill is the repo-intelligence package; the bare wheel works for
    the LLM-free commands (scan/map/dead-code-scan) out of the box, but full
    map fidelity needs the Tree-sitter and jedi extras and cold-start synthesis
    (run/bootstrap) needs a local LLM. The pip line is printed only for the extras
    the target interpreter cannot import, and the help pointer is a command the
    user can run, not a path in the TRW repo. No network, no disk writes.
    """
    if not any(entry.split(" ", 1)[0] == "trw-distill" for entry in installed):
        return
    ui.info("trw-distill installed — repo intelligence is ready:")
    ui.info("  trw-distill map  --repo .   # codebase map (LLM-free)")
    ui.info("  trw-distill scan --repo .   # git-history mining (LLM-free)")
    missing, verified = _missing_distill_map_extras(python or sys.executable, target)
    if missing:
        ui.info(
            "  Full map fidelity needs these packages, which this Python cannot import yet:"
            if verified
            else "  Full map fidelity needs these packages (could not check which are already installed):"
        )
        quoted = " ".join(f'"{requirement}"' for requirement in missing)
        ui.info(f"    python -m pip install {quoted}")
    ui.info("  Cold-start synthesis (trw-distill run/bootstrap) needs a local LLM (Ollama).")
    ui.info("  All commands and options: trw-distill --help")


def _emit_install_completed_event(
    target_dir: Path,
    installed: list[dict[str, str]],
    failed: list[str],
) -> None:
    """Emit a single JSONL line describing the proprietary install outcome.

    PRD-INFRA-130 FR04 + NFR02: the record contains package metadata and
    timestamps only \u2014 plaintext license keys are NEVER written. The file is
    append-only so historical runs are preserved (PRD-INFRA-130 NFR04).
    """
    import json as _json
    from datetime import datetime, timezone

    events_path = target_dir / ".trw" / "install-events.jsonl"
    events_path.parent.mkdir(parents=True, exist_ok=True)
    record = {
        "ts": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "event": "proprietary_install_completed",
        "target_dir": str(target_dir.resolve()),
        "packages": installed,
        "failed_packages": failed,
    }
    with events_path.open("a", encoding="utf-8") as fp:
        fp.write(_json.dumps(record, sort_keys=True) + "\n")


#: Where the proprietary-entitlement record lives, relative to the project root.
PROPRIETARY_MARKER_RELPATH = Path(".trw") / "proprietary-installed.json"


def read_proprietary_marker(target_dir: Path) -> dict[str, str]:
    """``{package: version}`` recorded by a prior proprietary install.

    Returns ``{}`` when the marker is absent, unreadable, or malformed, and
    drops any package name outside ``PROPRIETARY_PACKAGES_TUPLE`` — a hand-edited
    marker must not be able to widen what the installer fetches.
    """
    try:
        data = json.loads((target_dir / PROPRIETARY_MARKER_RELPATH).read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {}
    if not isinstance(data, dict):
        return {}
    return {
        str(name): str(version)
        for name, version in data.items()
        if name in PROPRIETARY_PACKAGES_TUPLE and isinstance(version, str) and version
    }


def write_proprietary_marker(target_dir: Path, installed: list[str]) -> Path | None:
    """Persist a record of which proprietary versions are installed.

    Read back by subsequent installs (``read_proprietary_marker``) to re-enable
    the proprietary path without the flag and to skip already-current packages
    (PRD-INFRA-126 NFR05 idempotency). Returns the marker path on success or
    None when there is nothing to record.

    MERGES over the prior record rather than replacing it: a run that fails to
    fetch an entitlement for one package must not erase the evidence that the
    package is installed, or the next run stops recognising the project as an
    entitled one.
    """
    if not installed:
        return None

    mapping: dict[str, str] = read_proprietary_marker(target_dir)
    for entry in installed:
        parts = entry.split()
        if len(parts) == 2:
            mapping[parts[0]] = parts[1]
    marker = target_dir / PROPRIETARY_MARKER_RELPATH
    marker.parent.mkdir(parents=True, exist_ok=True)
    marker.write_text(json.dumps(mapping, indent=2, sort_keys=True) + "\n")
    return marker


def _resolve_proprietary_from_marker(
    target_dir: Path,
    with_proprietary: bool,
    interactive: bool,
    ui: UI,
    offline: bool = False,
) -> bool:
    """Re-enable the proprietary path for a project that already has it.

    ``--with-proprietary`` / ``TRW_WITH_PROPRIETARY`` are per-invocation, but the
    entitlement is a property of the PROJECT. A user who installed the
    proprietary packages once and then re-ran the installer the ordinary way
    (``curl … | bash``, no env var) had trw-mcp/trw-memory upgraded underneath
    trw-distill, trw-metaharness, trw-loop and trw-swarm, which silently stayed
    at the previous release. The marker this install wrote is the record that
    says otherwise, and reading it is what makes it more than a write-only file.

    Non-interactive: yes, with an INFO line naming the marker so the decision is
    never invisible. Interactive: prompt, defaulting to yes. Two ways to decline
    without deleting the marker: answer no, or export
    ``TRW_WITH_PROPRIETARY=0`` (an explicit falsy value, which is the only
    opt-out a headless run has).

    ``offline`` short-circuits: the proprietary path is an entitlement POST plus
    a wheel download, and ``--offline`` already refuses to be combined with
    ``--with-proprietary``. Inferring the flag from a marker must not route
    around that refusal.
    """
    if with_proprietary:
        return True
    if offline:
        return False
    if _env_flag("TRW_WITH_PROPRIETARY") is False:
        return False
    entitled = read_proprietary_marker(target_dir)
    if not entitled:
        return False
    marker_path = target_dir / PROPRIETARY_MARKER_RELPATH
    packages = ", ".join(f"{name} {version}" for name, version in sorted(entitled.items()))
    if not interactive:
        ui.info(f"Proprietary packages recorded in {marker_path} ({packages}) — upgrading them too")
        return True
    ui.info(f"This project already has proprietary packages installed ({packages}).")
    ui.hint(f"Record: {marker_path}")
    if prompt_yes_no("Upgrade the proprietary packages as well?", default="y"):
        return True
    ui.step_warn("Proprietary packages left at their current versions")
    return False


def _version_status_payload(
    target_dir: Path, python: str, pip_target: str = "", ui: UI | None = None
) -> dict[str, object]:
    """Parsed ``trw-mcp version-status --project-root <target_dir>`` JSON.

    The probe seam for ``_deployed_framework_is_stale``: any failure to run or
    parse yields ``{}`` so the caller degrades to "not stale" rather than
    blocking the upgrade on a diagnostic error.

    A NON-ZERO exit is one of those failures. It used to be ignored: the JSON on
    stdout was parsed regardless, so a partially-written or error payload from a
    failed probe was read as a verdict about the project. The exit status is the
    only thing that distinguishes "the project is current" from "the probe could
    not tell you". Both still fail OPEN (the upgrade proceeds), but the failure
    is reported through *ui* with the return code and the tail of stderr rather
    than passing silently.
    """
    trw_cmd = find_trw_cmd(python, pip_target=pip_target)
    try:
        proc = subprocess.run(
            trw_cmd + ["version-status", "--project-root", str(target_dir)],  # noqa: RUF005 -- keeps this handler's baseline identity
            capture_output=True,
            text=True,
            timeout=60,
        )
        if proc.returncode != 0:
            if ui is not None:
                tail = (proc.stderr or "").strip().splitlines()
                detail = f": {tail[-1][:200]}" if tail else ""
                ui.step_warn(
                    f"version-status exited {proc.returncode} — cannot tell whether the "
                    f"deployed framework is current; continuing{detail}"
                )
            return {}
        data = json.loads(proc.stdout or "{}")
    except (OSError, ValueError, subprocess.SubprocessError):
        return {}
    return data if isinstance(data, dict) else {}


def _deployed_framework_is_stale(target_dir: Path, python: str, pip_target: str = "", ui: UI | None = None) -> bool:
    """True when the project's DEPLOYED assets are behind the installed package.

    An ``--upgrade`` run bumps the trw-mcp package but skips project setup, so the
    deployed framework bodies + config (``.trw/frameworks/``, ``.trw/config.yaml``)
    can drift behind the package. Detected via ``trw-mcp version-status``.

    Comparing ONLY ``framework_protocol_version`` against ``installed_asset_version``
    -- what this did until 2026-09-07 -- was a check that could not fire in practice:
    both are the framework PROTOCOL version, which is deliberately stable across
    package releases (unchanged since 2026-07-27, identical on 1.0.5 and 2.0.1). So
    ``install-trw.py --upgrade`` printed "framework already current" and never ran
    update-project, and every user upgrading a package kept the previous release's
    deployed assets. The signal that actually moves per release is the resolved
    package version recorded in ``.trw/managed-artifacts.yaml`` ``packages``
    (PRD-INFRA-192 FR12 — VERSION.yaml no longer carries a package-version
    stamp), and ``version-status`` already computes the whole comparison
    (``installed_packages`` vs. ``manifest_packages``) as ``mismatches``.

    Stale when ANY of: the asset manifest is absent; the protocol versions differ;
    or ``version-status`` reported any mismatch at all (including
    ``manifest_packages_missing`` / ``trw_mcp_installed_vs_manifest``). Best-effort:
    an unparseable or empty payload returns False, so a probe error never blocks
    the upgrade.
    """
    data = _version_status_payload(target_dir, python, pip_target=pip_target, ui=ui)
    versions = data.get("versions", {})
    if not isinstance(versions, dict):
        return False
    if versions.get("installed_asset_present") is False:
        return True
    pkg_fw = versions.get("framework_protocol_version")
    deployed_fw = versions.get("installed_asset_version")
    if pkg_fw and deployed_fw and pkg_fw != deployed_fw:
        return True
    mismatches = data.get("mismatches")
    return bool(isinstance(mismatches, list) and mismatches)


def _run_project_command(ui: UI, label: str, cmd: list[str], ok_msg: str, fail_msg: str) -> None:
    """Run one init/update-project call; on failure stop the installer before any further project write.

    A refused or failed update-project rolls its own changes back. Carrying on to
    rewrite config.yaml and VERSION.yaml after it would half-apply the install the
    command just declined (PRD-INFRA-192 NFR02), so the child's error lines, which
    name the remedy, are shown and the installer exits non-zero.
    """
    output: list[str] = []
    ok = run_with_progress(ui, label, cmd, output=output)
    ui.stop_spinner(ok, ok_msg, fail_msg)
    if ok:
        return
    for line in [line for line in output if "error" in line.lower()][-10:]:
        ui.error(line)
    ui.step_fail(f"{fail_msg}; stopping before any further change to the project")
    sys.exit(1)


def phase_project_setup(
    ui: UI,
    step: int,
    total: int,
    python: str,
    target_dir: Path,
    upgrade_only: bool,
    interactive: bool = False,
    ide: list[str] | None = None,
    pip_target: str = "",
) -> list[str]:
    """Set up or update the project scaffolding."""
    ui.step_header(step, total, "Setting up project")

    if upgrade_only:
        # An --upgrade run bumps the package but otherwise skips project setup, so
        # a prior install's deployed framework bodies + config can drift out of
        # date (e.g. a v25_TRW project on a v26.1 package). When the deployed
        # framework is stale/deprecated relative to the freshly-installed package,
        # refresh it with `trw-mcp update-project` (idempotent; preserves user
        # config). Skip when there is no prior install or it is already current.
        prior = _load_prior_config(target_dir, ui)
        prior_targets = prior.get("target_platforms", [])
        if not isinstance(prior_targets, list):
            prior_targets = []
        has_prior_install = (target_dir / ".trw" / "installer-meta.yaml").is_file() or bool(prior_targets)
        if has_prior_install and _deployed_framework_is_stale(target_dir, python, pip_target, ui=ui):
            targets = _normalize_ide_targets([str(t) for t in prior_targets])
            if not targets:
                # Defaulting to claude-code here would scaffold a client surface
                # the user never asked for (.claude/, AGENTS.md, hooks) into a
                # project that records none. An upgrade is not the place to guess
                # — say what is missing and let the operator name the client.
                ui.step_warn(
                    "Deployed framework is out of date, but no client is recorded in "
                    ".trw/config.yaml (target_platforms) — skipping the refresh. "
                    "Re-run without --upgrade, or with --ide <client>, to refresh it."
                )
                return []
            trw_cmd = find_trw_cmd(python, pip_target=pip_target)
            ui.step_ok("Deployed framework is out of date — refreshing with update-project")
            # One plain update-project, as the ordinary path runs it (E2E-INC-135). Without --ide it resolves the
            # recorded clients itself; a per-client `--ide X` narrowed each run to X and left surfaces the plain
            # run refreshes (the Copilot hook lib) stale, so doctor failed after a "successful" upgrade.
            labels = ", ".join(_ide_label(t) for t in targets)
            _run_project_command(
                ui,
                f"Updating framework for {labels}...",
                [*trw_cmd, "update-project", str(target_dir)],
                f"Framework updated for {labels}",
                f"update-project failed for {labels}",
            )
        else:
            ui.step_ok("Upgrade complete — framework already current")
        return []

    if not (target_dir / ".git").is_dir():
        # PRD-INFRA-170-FR06 / OQ-1: do NOT bail here. The framework bodies
        # deploy git-independently (init-project step 9 -> repair_framework_runtime
        # under .trw/frameworks/). Returning early is exactly what left users with
        # a config-present, framework-absent half-install. Warn loudly, then fall
        # through to the real init so the framework deploys even in a non-git dir.
        ui.step_warn("Not a git repository — installing the framework anyway")
        ui.step_warn("Run 'git init' to enable git-based features.")

    # IDE detection and selection
    detected_clis = _detect_installed_clis()
    detected_ides = _detect_project_ides(str(target_dir))
    prior_config = _load_prior_config(target_dir, ui)
    prior_targets = prior_config.get("target_platforms", [])
    if not isinstance(prior_targets, list):
        prior_targets = []

    # A real prior install writes ``.trw/installer-meta.yaml`` (init-project /
    # update-project). The mere existence of ``.trw/`` is NOT sufficient — the
    # bash bootstrap pre-creates ``.trw/`` so ``trw-mcp auth login`` can save
    # config.yaml, which would otherwise trip the update branch and silently
    # auto-select detected clients without prompting (see install-trw.py
    # phase_project_setup PRD-FIX-???).
    has_prior_install = (target_dir / ".trw" / "installer-meta.yaml").is_file() or bool(prior_targets)

    resolved_targets: list[str] | None = ide
    is_update = (target_dir / ".trw").is_dir() and has_prior_install
    if resolved_targets is None:
        if has_prior_install and interactive and prior_targets:
            resolved_targets = _normalize_ide_targets(prior_targets)
            ui.step_ok(f"Client surfaces: {_format_ide_list(resolved_targets)} (from prior install)")
        elif interactive:
            # First-time install (no installer-meta.yaml) OR a prior install with
            # no recorded target_platforms: always prompt so users know which
            # clients TRW is being configured for.
            resolved_targets = _prompt_ide_selection(detected_clis, detected_ides, prior_targets=prior_targets)
        else:
            # Headless: reuse prior targets, else the default client set (detection is advisory only).
            resolved_targets = _normalize_ide_targets(prior_targets or _DEFAULT_IDES)
            if not resolved_targets:
                resolved_targets = _DEFAULT_IDES.copy()

    if not resolved_targets:
        ui.step_warn("Skipping client surface setup — re-run install-trw.py or trw-mcp update-project later")
        return []

    trw_cmd = find_trw_cmd(python, pip_target=pip_target)
    first_action = "update-project" if is_update else "init-project"

    for idx, selected_ide in enumerate(resolved_targets):
        action = first_action if idx == 0 else "update-project"
        label = "Updating" if action == "update-project" else "Initializing"
        success_message = (
            f"{_ide_label(selected_ide)} configured"
            if len(resolved_targets) > 1
            else f"Project {'updated' if is_update else 'initialized'}"
        )
        _run_project_command(
            ui,
            f"{label} project for {_ide_label(selected_ide)}...",
            [*trw_cmd, action, str(target_dir), "--ide", selected_ide],
            success_message,
            f"Project {action} failed for {_ide_label(selected_ide)}",
        )

    config_path = target_dir / ".trw" / "config.yaml"
    refreshed_config = _load_prior_config(target_dir, ui)
    project_name = str(refreshed_config.get("project_name", sanitize_project_name(target_dir.name)))
    api_key = str(refreshed_config.get("api_key", ""))
    telemetry_enabled = bool(refreshed_config.get("telemetry", False))
    # UNION, never replace. `update_config` rewrites the target_platforms block
    # wholesale, but the recorder it runs after — bootstrap
    # `_update_config_target_platforms` — is append-only BY DESIGN (PRD-FIX-076):
    # it exists so a single-client run cannot silently un-configure the client
    # surfaces a user already has. Passing only this run's targets threw that
    # away as the last write, so `--ide codex` on a [claude-code, codex] project
    # narrowed the list to [codex] and the next bare update-project stopped
    # maintaining the Claude Code surface.
    recorded_targets = refreshed_config.get("target_platforms", [])
    if not isinstance(recorded_targets, list):
        recorded_targets = []
    merged_targets = _unique([str(t) for t in recorded_targets] + list(resolved_targets))
    update_config(
        config_path,
        project_name,
        api_key,
        telemetry_enabled,
        target_platforms=merged_targets,
    )
    # PRD-SEC-005-FR01: persist the bearer credential to the ignored, 0600
    # credentials.yaml — config.yaml never receives the secret.
    write_platform_credentials(config_path, api_key)

    return resolved_targets


# A doctor that does not finish is INCOMPLETE, never FAILED (feedback #155).
_DOCTOR_TIMEOUT_SECONDS = 60


def _load_note() -> str:
    """``load average 1.2/3.4/5.6 on 8 CPUs`` for a doctor that timed out; ``""`` where the OS reports none."""
    try:
        one, five, fifteen = os.getloadavg()
    except (AttributeError, OSError):  # trw-fail-silent-allow: no load figure on this OS; the note is advisory
        return ""
    return f"load average {one:.1f}/{five:.1f}/{fifteen:.1f} on {os.cpu_count() or '?'} CPUs"


def _run_doctor_command(ui: UI, cmd: list[str]) -> subprocess.CompletedProcess[str] | None:
    """Run the doctor; ``None`` (already reported, neutrally) if it never finished."""
    try:
        return subprocess.run(cmd, capture_output=True, text=True, timeout=_DOCTOR_TIMEOUT_SECONDS, check=False)
    except subprocess.TimeoutExpired:
        load = _load_note()
        ui.step_warn(
            f"'trw-mcp doctor' did not complete in {_DOCTOR_TIMEOUT_SECONDS}s"
            + (f" ({load})" if load else "")
            + "; this says nothing about the install. Run 'trw-mcp doctor' to check it."
        )
    except (OSError, subprocess.SubprocessError) as exc:
        ui.step_warn(f"Could not run 'trw-mcp doctor' ({exc}); run it manually to check the install.")
    return None


#: The Dispatch line the setup step printed this run (PRD-INFRA-210 FR09): shown beside ``Extras:`` in the banner.
_DISPATCH_LINE = ""


def dispatch_line() -> str:
    """The step's one ``Dispatch: ...`` line from this run, or ``""`` when the step did not report one."""
    return _DISPATCH_LINE


def build_dispatch_args(*, with_dispatch: bool, no_dispatch: bool, models: list[str], efforts: list[str]) -> list[str]:
    """The ``trw-mcp config dispatch`` arguments the installer's flags and environment ask for (PRD-INFRA-210 FR08/FR10).

    ``--with-dispatch`` / ``--no-dispatch`` win over ``TRW_WITH_DISPATCH`` (1/true/yes enable, 0/false/no disable,
    anything else is unset). Pins are forwarded as given; ``TRW_DISPATCH_MODELS`` / ``TRW_DISPATCH_EFFORTS`` stay in
    the inherited environment, which the step reads itself.
    """
    env = _env_flag("TRW_WITH_DISPATCH")
    enable = with_dispatch or (env is True and not no_dispatch)
    disable = no_dispatch or (env is False and not with_dispatch)
    args = ["--enable"] * (enable and not disable) + ["--disable"] * (disable and not enable)
    for flag, pins in (("--dispatch-model", models), ("--dispatch-effort", efforts)):
        for pin in pins:
            args += [flag, pin]
    return args


_STEP_WARNING_PREFIX = "config dispatch: warning: "
_SECRET_LIKE = re.compile(r"trw_(?:dk_)?[A-Za-z0-9_-]{16,}")


def _safe_step_text(text: str) -> str:
    """A step warning made safe to print: control characters dropped, any API key (env or ``trw_...`` shaped) masked."""
    for name in ("TRW_API_KEY", "TRW_PLATFORM_API_KEY"):
        secret = os.environ.get(name, "").strip()
        if secret:
            text = text.replace(secret, "[redacted]")
    text = _SECRET_LIKE.sub("[redacted]", text)
    return "".join(ch for ch in text if ch.isprintable()).strip()


def run_dispatch_step(ui: UI, trw_cmd: list[str], target_dir: Path, extra: tuple[str, ...]) -> None:
    """Run ``trw-mcp config dispatch`` (PRD-INFRA-210 FR08): advisory, one warning on any failure, never raises.

    Interactive runs pass ``--offer`` and read the printed Dispatch line (``--json`` is a machine mode that never
    asks); every other run asks for ``--json`` and reads its ``line``. The step's own warnings are shown.
    """
    global _DISPATCH_LINE
    _DISPATCH_LINE = ""
    machine = not ui.interactive
    cmd = [*trw_cmd, "config", "dispatch", str(target_dir), *(["--offer"] if ui.interactive else []), *extra]
    cmd += ["--json"] * machine
    failure = "it could not run"
    try:
        proc = subprocess.run(cmd, capture_output=True, text=True, timeout=120, check=False)
        if proc.returncode != 0:
            failure = f"it exited {proc.returncode}"
        elif machine:
            payload = json.loads(proc.stdout)
            _DISPATCH_LINE = str(payload.get("line") or "")
            for warning in payload.get("warnings", []):
                ui.step_warn(f"Dispatch setup: {_safe_step_text(str(warning))}")
            return
        else:
            lines = [ln.strip() for ln in proc.stdout.splitlines() if ln.strip().startswith("Dispatch:")]
            _DISPATCH_LINE = _safe_step_text(lines[-1]) if lines else ""
            # An invalid pin or a refused write exits 0 and says so on stderr: relay each, never drop it.
            for raw in proc.stderr.splitlines():
                if raw.startswith(_STEP_WARNING_PREFIX):
                    ui.step_warn(f"Dispatch setup: {_safe_step_text(raw.removeprefix(_STEP_WARNING_PREFIX))}")
            return
    except (OSError, subprocess.SubprocessError, ValueError, AttributeError) as exc:
        failure = f"it failed ({type(exc).__name__})"
    ui.step_warn(f"Dispatch setup was not completed ({failure}); run 'trw-mcp config dispatch .' to set it up.")


def run_install_doctor(
    ui: UI,
    python: str,
    target_dir: Path,
    pip_target: str = "",
    dispatch_args: tuple[str, ...] = (),
) -> bool | None:
    """PRD-INFRA-170-FR06: run ``trw-mcp doctor`` at install end.

    Returns True when the deployed framework is healthy (no FAIL check) and False when a check FAILed. On any
    FAIL check, emit a LOUD, non-silent warning naming the failing checks and the
    single remediation command — never a silent green success line. A WARN row
    does not fail the install, but it is never reported as "passed" either: the
    line gives the count and the names, so it matches the doctor's own verdict.

    Returns None (incomplete) when the doctor could not run, ran out of time, or printed nothing parseable: that says
    nothing about the framework, so the banner stays neutral (feedback #155). Never aborts the install.
    """
    trw_cmd = find_trw_cmd(python, pip_target=pip_target)
    # trw_assess (jev) first: inherit the machine key (~/.trw/jev.env) in one line, or offer once (interactive only)
    # to promote a key found only in this project's .env. Never writes the key into a project file; advisory.
    subprocess.run([*trw_cmd, "assess", "install-check", str(target_dir), *["--offer"] * ui.interactive], check=False)
    run_dispatch_step(ui, trw_cmd, target_dir, dispatch_args)  # PRD-INFRA-210 FR08: after assess, advisory
    proc = _run_doctor_command(ui, [*trw_cmd, "doctor", str(target_dir), "--format", "json"])
    if proc is None:
        return None
    try:
        payload = json.loads(proc.stdout)
        checks = payload.get("checks", [])
    except (ValueError, AttributeError):  # trw-fail-silent-allow: reported via step_warn; the verdict is incomplete
        ui.step_warn("Could not parse 'trw-mcp doctor' output; run 'trw-mcp doctor' manually to check the install.")
        return None
    failed = [
        (str(check.get("name", "?")), str(check.get("message", "")).strip())
        for check in checks
        if isinstance(check, dict) and check.get("status") == "FAIL"
    ]
    if failed:
        ui.step_warn("trw-mcp doctor reported problems with the installed framework:")
        for name, message in failed:
            # FB-INSTALL-01: the row's own message says what broke and how to fix it (the generic fix
            # below does not repair e.g. a hook family whose lib is out of date).
            ui.step_warn(f"  FAIL: {name}: {message}" if message else f"  FAIL: {name}")
        messages = [message for _name, message in failed]
        # The remedy follows what failed (E2E-INC-131): `git init && init-project` is only right for a project that
        # was never initialised, and it was printed over a daemon_version_mismatch in an initialised repository.
        if any("daemon_version_mismatch" in m for m in messages):
            ui.step_warn(
                "Fix: a memory daemon of an older version is still serving. The user stops it (its pid is named "
                "above); the next TRW call starts the new one. Then run 'trw-mcp doctor' again."
            )
        elif any("init-project" in m for m in messages):
            ui.step_warn("Fix: run 'trw-mcp init-project .' in this directory (add 'git init &&' if it is not a repo).")
        else:
            ui.step_warn("Fix: see the message above, then run 'trw-mcp doctor' again to confirm.")
        return False
    warned = [c for c in checks if isinstance(c, dict) and c.get("status") == "WARN"]
    if warned:
        noun = "warning" if len(warned) == 1 else "warnings"
        names = ", ".join(str(c.get("name", "?")) for c in warned)
        ui.step_warn(f"Framework health check: {len(warned)} {noun} ({names}); run 'trw-mcp doctor' for details")
        # FB-INSTALL-05 a: a row's own remedy ('fix: trw-mcp memory reembed') is printed, not left to the doctor.
        for c in (c for c in warned if "fix:" in str(c.get("message", ""))):
            ui.step_warn(f"  {c.get('name', '?')}: {str(c['message']).strip()}")
        return True
    ui.step_ok("Framework health check passed (trw-mcp doctor: no failures)")
    return True


def phase_semantic_readiness(
    ui: UI,
    python: str,
    *,
    interactive: bool,
    pip_target: str = "",
    offline: bool = False,
) -> str:
    """Make semantic retrieval work, on EVERY invocation that wants embeddings.

    Only called when embeddings are wanted (the default; see
    :func:`resolve_embeddings_choice`). Like :func:`run_install_doctor` it is an
    unnumbered end-of-install check, so the step count stays stable.

    Non-interactive (``--script``, CI, ``curl | sh`` with no controlling
    terminal): repair without asking — install the extra, then cache the model.
    Interactive: ask first (default yes); a "no" returns :data:`SEMANTIC_DECLINED`,
    the same choice as ``--no-embeddings``. Offline: nothing can be fetched, so a
    gap stays a gap. Any status other than OK or DECLINED is a failed install:
    ``main`` finishes setup and exits non-zero.

    Returns the FINAL status after any repair attempt.
    """
    validated_target = validate_pip_target(pip_target)
    model = daemon_embedding_model(python, target_dir=validated_target)
    status = probe_semantic_stack(python, model, target_dir=validated_target)
    if status == SEMANTIC_OK:
        # Idempotent: a healthy re-run prints one calm line and changes nothing.
        ui.step_ok(f"Semantic retrieval ready (sentence-transformers + {model} weights cached)")
        return status
    if status == SEMANTIC_UNKNOWN:
        ui.step_warn(
            f"Could not verify semantic retrieval in {python} (the configured model or the probe did not resolve)."
        )
        ui.step_warn("  Check it with: trw-mcp doctor   (the 'retrieval' row names the fix)")
        return status

    # The one fetch path, at the pinned revision the runtime loads (PRD-CORE-302 FR06, W46).
    download_fix = f"{python} -m trw_mcp.server models fetch"
    if status == SEMANTIC_MISSING_LIBRARY:
        ui.step_warn("Semantic retrieval is NOT active: sentence-transformers / torch are missing.")
        fix = f"{python} -m pip install '{SEMANTIC_EXTRA_SPEC}'  &&  {download_fix}"
        question = f"Install the semantic-embeddings stack now ({SEMANTIC_EXTRA_SPEC}, several hundred MB with torch)?"
    else:  # SEMANTIC_MISSING_WEIGHTS
        ui.step_warn(f"Semantic retrieval is NOT active: the {model} weights are not in the local cache.")
        fix = download_fix
        question = f"Download the embedding model now ({model})?"
    ui.step_warn(f"  Interpreter checked: {python}")
    ui.step_warn(f"  Fix: {fix}")

    if offline:
        ui.step_warn(
            "  Offline mode: nothing can be fetched — run the fix when online, or re-run with --no-embeddings."
        )
        return status
    if interactive and not prompt_yes_no(question, default="y"):
        ui.hint("Embeddings off: recall is keyword-only (recorded as embeddings_enabled: false).")
        return SEMANTIC_DECLINED

    if status == SEMANTIC_MISSING_LIBRARY:
        ui.start_spinner(f"Installing {SEMANTIC_EXTRA_SPEC}...")
        ok = pip_install(python, SEMANTIC_EXTRA_SPEC, SEMANTIC_EXTRA_SPEC, ui, target_dir=validated_target)
        ui.stop_spinner(ok, "Embeddings package installed", "Embeddings install failed")
        if not ok:
            return status
        status = probe_semantic_stack(python, model, target_dir=validated_target)

    if status == SEMANTIC_MISSING_WEIGHTS:
        ui.start_spinner(f"Downloading {model}...")
        ok = download_semantic_model(python, model, target_dir=validated_target)
        ui.stop_spinner(ok, "Embedding model cached", "Model download failed")
        if not ok:
            return status
        status = probe_semantic_stack(python, model, target_dir=validated_target)

    if status == SEMANTIC_OK:
        ui.step_ok("Semantic retrieval ready")
    return status


def resolve_embeddings_choice(flag: bool | None, prior_config: dict[str, object]) -> bool:
    """Whether this install wants embeddings: the flag, else a prior opt-out, else on.

    A prior ``embeddings_enabled: false`` is honoured on a re-run without a flag,
    so a reinstall never silently undoes an operator's opt-out; ``--embeddings``
    re-enables it.
    """
    if flag is not None:
        return flag
    return prior_config.get("embeddings") is not False


def persist_embeddings_choice(config_path: Path, enabled: bool) -> None:
    """Record the choice as ``embeddings_enabled`` so doctor reports an opt-out as a choice, not a fault."""
    if not config_path.is_file() or config_path.is_symlink() or config_path.parent.is_symlink():
        return  # a symlinked managed path is update-project's to refuse; never write through one
    line = f"embeddings_enabled: {'true' if enabled else 'false'}\n"
    lines = config_path.read_text(encoding="utf-8").splitlines(keepends=True)
    kept = [existing for existing in lines if not existing.startswith("embeddings_enabled:")]
    if kept and not kept[-1].endswith("\n"):
        kept[-1] += "\n"
    config_path.write_text("".join([*kept, line]), encoding="utf-8")


def report_semantic_failure(ui: UI, status: str) -> None:
    """The loud end of an install whose embeddings were wanted but do not work."""
    ui.step_fail(f"Install incomplete: semantic retrieval is not active ({status}).")
    ui.step_fail("  Run the fix printed above and re-run this installer,")
    ui.step_fail("  or re-run with --no-embeddings to install keyword-only recall on purpose.")


# ── Checkout store -> user store (PRD-CORE-280 FR03, 6.1.0) ──────────
#
# trw-mcp 6 reads learnings only from the user store, through the memory
# daemon. A checkout upgraded from 5.x keeps them in .trw/memory/memory.db,
# where nothing reads them until `trw-mcp memory migrate --to user --apply`
# runs, so the installer runs it. The command backs the store up first and, on
# an id the user store holds with other content, refuses and moves nothing.

#: Exit code of :data:`_HOLDS_ROWS_SOURCE` when the store holds no learning.
_HOLDS_NO_ROWS = 3
#: ``trw-mcp memory migrate`` exits 2 on a refusal a rerun clears: another
#: process holds the store, or the daemon answered busy or uncertain.
_MIGRATE_RETRY = 2
_MIGRATED_PREFIX = "memory migrate: migrated; manifest "

# The same check update-project and doctor use, run in the target interpreter.
_HOLDS_ROWS_SOURCE = (
    "import sys\n"
    "from pathlib import Path\n"
    "from trw_mcp.state._store_migration import holds_rows\n"
    f"sys.exit(0 if holds_rows(Path(sys.argv[1])) else {_HOLDS_NO_ROWS})\n"
)


def _run_migrate_command(cmd: list[str], cwd: Path, target_dir: str = "") -> tuple[int, str, str]:
    """Run *cmd* from the project in the target interpreter's environment; ``(exit code, stdout, stderr)``."""
    env = _build_pip_runtime_env(target_dir)
    if target_dir:
        env["PYTHONPATH"] = target_dir + os.pathsep + env.get("PYTHONPATH", "")
    try:
        proc = subprocess.run(cmd, cwd=cwd, env=env, capture_output=True, text=True, timeout=600)
    except (OSError, subprocess.TimeoutExpired) as exc:
        return 1, "", f"memory migrate could not run: {exc}"
    return proc.returncode, proc.stdout or "", proc.stderr or ""


def phase_migrate_store(
    ui: UI, python: str, target_dir: Path, *, migrate: bool, interactive: bool, pip_target: str = ""
) -> bool:
    """Move the checkout store's learnings into the user store; False when the install must exit non-zero."""
    db = target_dir / ".trw" / "memory" / "memory.db"
    if not db.is_file():
        return True
    manual = f"trw-mcp memory migrate --to user --apply --target-dir {target_dir}"
    code, _ = _run_python_output([python, "-B", "-c", _HOLDS_ROWS_SOURCE, str(db)], target_dir=pip_target)
    if code == _HOLDS_NO_ROWS:
        return True
    if code != 0:
        ui.step_fail(f"Could not tell whether {db} holds learnings trw-mcp no longer reads.")
        ui.error(f"  Check with `trw-mcp doctor`, then move them with: {manual}")
        return False
    unread = f"{db} holds learnings trw-mcp 6 no longer reads"
    if not migrate or (
        interactive
        and not prompt_yes_no("Move this checkout's learnings into the user store now (backed up first)?", default="y")
    ):
        ui.step_warn(f"{unread}; move them with: {manual}")
        return True
    ui.start_spinner("Moving this checkout's learnings into the user store...")
    code, out, err = _run_migrate_command(
        [
            python,
            "-B",
            "-m",
            "trw_mcp.server",
            "memory",
            "migrate",
            "--to",
            "user",
            "--apply",
            "--target-dir",
            str(target_dir),
        ],
        cwd=target_dir,
        target_dir=pip_target,
    )
    ui.stop_spinner(code == 0, "Learnings moved into the user store", "Learnings were not moved")
    manifest = next(
        (line[len(_MIGRATED_PREFIX) :].strip() for line in out.splitlines() if line.startswith(_MIGRATED_PREFIX)), ""
    )
    for line in [line for line in (out + err).splitlines() if line.strip() and not line.startswith(_MIGRATED_PREFIX)]:
        (ui.info if code == 0 else ui.error)(f"  {line}")
    if code == 0:
        ui.step_ok(f"Migration manifest: {manifest}")
        ui.info(f"  Undo: trw-mcp memory migrate --to user --rollback {manifest} --target-dir {target_dir}")
        return True
    if code == _MIGRATE_RETRY:
        ui.step_fail(f"{unread}: the move did not finish (busy or uncertain), and nothing was cut over.")
        ui.error(f"  Stop the clients listed above, then re-run install-trw.py or: {manual}")
    else:
        ui.step_fail(f"{unread}: the migration refused, and nothing was moved or forced.")
        ui.error(f"  Resolve the ids named above (see `trw-mcp doctor`), then run: {manual}")
    return False


def _resolve_interactive_telemetry(
    ui: UI,
    *,
    opt_telemetry: bool | None,
    prior_config: dict[str, object],
) -> bool:
    """Resolve the telemetry opt-in for an interactive install (FR02/FR07).

    Precedence (highest first):
      1. An explicit ``--telemetry`` / ``--no-telemetry`` flag forwarded through
         install.sh — honored verbatim, no prompt (FR02/FR03).
      2. A prior ``platform_telemetry_enabled`` recorded in config — the earlier
         answer, reused without asking again, so an upgrade neither re-asks nor
         flips a recorded opt-out (FR07; the 9.0.1 upgrade report: asked on every
         upgrade).
      3. Otherwise, an explicit yes/no consent prompt that defaults to OFF.

    The presence of an API key NEVER force-enables telemetry: usage telemetry is
    consented independently of platform connection (FR02).
    """
    if opt_telemetry is True:
        ui.step_ok("Telemetry enabled (--telemetry)")
        return True
    if opt_telemetry is False:
        ui.step_ok("Telemetry disabled (--no-telemetry)")
        return False

    if "telemetry" in prior_config:
        recorded = bool(prior_config["telemetry"])
        state = "enabled" if recorded else "disabled"
        ui.step_ok(f"Telemetry {state} (your earlier choice; --telemetry or --no-telemetry changes it)")
        return recorded

    print()
    ui.hint("Pseudonymous usage telemetry helps us improve TRW for everyone.")
    ui.hint("Only tool-usage counts are shared — never your code or learnings.")
    ui.doc_link_url(_PRIVACY_DOC_URL)
    telemetry_enabled = prompt_yes_no("Enable pseudonymous usage telemetry?", default="n")
    ui.step_ok("Telemetry enabled" if telemetry_enabled else "Telemetry disabled")
    return telemetry_enabled


def phase_configure(
    ui: UI,
    step: int,
    total: int,
    target_dir: Path,
    interactive: bool,
    opt_name: str,
    opt_api_key: str,
    opt_telemetry: bool | None,
    prior_config: dict[str, object] | None = None,
    *,
    skip_auth: bool = False,
    target_platforms: list[str] | None = None,
) -> str:
    """Configure project identity, API key, and telemetry. Returns platform_status."""
    ui.step_header(step, total, "Configure your project")

    if prior_config is None:
        prior_config = {}

    default_name = sanitize_project_name(target_dir.name)
    project_name = ""
    api_key = ""
    telemetry_enabled = False

    prior_name = _reusable_prior_name(ui, prior_config)
    if interactive:
        if prior_name:
            project_name = prior_name
            ui.step_ok(f"Project: {project_name} (installation_id in .trw/config.yaml, from prior install)")
        else:
            draw_divider("Project Identity")
            print()
            ui.hint("This name identifies your installation in the TRW platform.")
            ui.hint("It appears in your analytics dashboard and team views.")
            project_name = _prompt_project_name(ui, default_name)

        if prior_config.get("api_key"):
            ui.step_ok("API key: configured (from prior install)")
            api_key = str(prior_config["api_key"])
        elif skip_auth and opt_api_key and validate_api_key(opt_api_key):
            api_key = opt_api_key
            ui.step_ok("API key: accepted (from bootstrap)")
        elif skip_auth:
            ui.step_ok("Auth skipped (--skip-auth)")
        else:
            draw_divider("Platform Connection")
            print()
            ui.hint("Connect to trwframework.com to sync learnings across")
            ui.hint("machines, view analytics, and collaborate with your team.")
            ui.doc_link_url(_PRIVACY_DOC_URL)
            api_key = _prompt_api_key(ui)

        # PRD-SEC-004-FR02: telemetry consent is ALWAYS explicit. A configured
        # API key (whether from prior install, bootstrap, or fresh device auth)
        # must NEVER force-enable telemetry — the consent prompt is reachable on
        # every interactive path. PRD-SEC-004-FR07: a prior opt-out is the
        # default and is never silently re-enabled.
        telemetry_enabled = _resolve_interactive_telemetry(ui, opt_telemetry=opt_telemetry, prior_config=prior_config)
    else:
        # Script mode: use flags
        project_name = sanitize_project_name(opt_name) if opt_name else (prior_name or default_name)
        # PRD-FIX-067-FR02: Check prior_config before opt_api_key
        if prior_config.get("api_key"):
            api_key = str(prior_config["api_key"])
            ui.step_ok("API key: configured (from prior install)")
        elif opt_api_key:
            if validate_api_key(opt_api_key):
                api_key = opt_api_key
            else:
                ui.warn("Invalid API key format — ignoring --api-key")
        # PRD-SEC-004-FR02: script mode defaults telemetry OFF; an API key alone
        # never enables it. PRD-SEC-004-FR07: a prior opt-in/opt-out is preserved
        # when no explicit flag is given, and an explicit --no-telemetry always
        # wins. PRD-SEC-004-FR03: --telemetry/--no-telemetry are forwarded here
        # from install.sh.
        if opt_telemetry is True:
            telemetry_enabled = True
        elif opt_telemetry is False:
            telemetry_enabled = False
        elif "telemetry" in prior_config:
            telemetry_enabled = bool(prior_config["telemetry"])
        else:
            telemetry_enabled = False
        ui.step_ok(f"Project: {project_name}")
        ui.step_ok("Telemetry enabled" if telemetry_enabled else "Telemetry disabled")

    preserve_prior_platform_urls = bool(prior_config.get("platform_urls")) and not opt_api_key and opt_telemetry is None

    # Write to config (including feature flags for future reinstall detection)
    config_path = target_dir / ".trw" / "config.yaml"
    if update_config(
        config_path,
        project_name,
        api_key,
        telemetry_enabled,
        target_platforms=target_platforms or None,
        rewrite_platform_urls=not preserve_prior_platform_urls,
    ):
        # PRD-SEC-005-FR01: store the bearer credential in the ignored, 0600
        # credentials.yaml rather than the git-tracked config.yaml.
        write_platform_credentials(config_path, api_key)
        ui.step_ok("Configuration saved to .trw/config.yaml")
    else:
        ui.step_warn("Config file not found — run project setup first")

    if api_key:
        return "connected"
    if telemetry_enabled:
        return "telemetry"
    return "offline"


def _prompt_project_name(ui: UI, default: str) -> str:
    """Interactive project name prompt with sanitization."""
    raw = prompt_input("Project name:", default)
    name = sanitize_project_name(raw) or default
    if not re.match(r"^[a-z0-9]([a-z0-9-]*[a-z0-9])?$", name):
        ui.step_warn("Could not sanitize name, using default")
        name = default
    if name != raw and raw:
        ui.step_ok(f"Project name: {name} (sanitized from '{raw}')")
    else:
        ui.step_ok(f"Project name: {name}")
    return name


def _prompt_api_key(ui: UI) -> str:
    """Interactive API key prompt -- asks consent, then tries device auth, falls back to manual paste.

    Device authorization (RFC 8628) opens a browser for passwordless login and
    posts a device-code request to the platform before any key is entered.
    PRD-INFRA-200 FR06: that network call and browser tab must never fire
    without the operator saying yes first. Declining (or a non-interactive run,
    where ``prompt_yes_no``'s own no-TTY fallback returns the default "n") skips
    straight to the manual-paste fallback with zero calls made.
    """
    if prompt_yes_no("Sign in via browser (device authorization)?", default="n"):
        try:
            result = _device_auth_login(API_BASE, interactive=True)
            if result and isinstance(result.get("api_key"), str) and result["api_key"]:
                key = str(result["api_key"])
                if validate_api_key(key):
                    ui.step_ok("Authenticated via device flow")
                    return key
        except Exception:  # device auth is best-effort, fall back to manual
            pass

    # Fallback: manual key entry
    print()
    ui.hint("Or paste an API key manually:")
    max_attempts = 3
    for attempt in range(max_attempts):
        raw = prompt_input("Platform API key (Enter to skip):").strip()
        if not raw:
            ui.step_ok("No API key -- offline mode")
            return ""
        if validate_api_key(raw):
            ui.step_ok("API key accepted")
            return raw
        remaining = max_attempts - attempt - 1
        if remaining > 0:
            ui.step_warn(
                "Invalid format (must start with trw_ or trw_dk_, then base64url chars: letters, digits, _ or -). Try again:"
            )
        else:
            ui.step_warn("Invalid format -- skipping API key")
    return ""


def _device_auth_login(api_url: str, interactive: bool = True) -> dict[str, Any] | None:
    """Perform RFC 8628 device authorization -- stdlib only.

    Inline implementation that avoids importing trw_mcp.cli.auth (which may
    not be installed when running the standalone installer script).
    """
    import json as _json
    import time as _time
    import urllib.error
    import urllib.request
    import webbrowser as _wb

    api_url = api_url.rstrip("/")

    # Step 1: Request device code
    try:
        body = _json.dumps({"client_id": "trw-cli"}).encode("utf-8")
        req = urllib.request.Request(
            f"{api_url}/v1/auth/device/code",
            data=body,
            method="POST",
            headers={"Content-Type": "application/json"},
        )
        with urllib.request.urlopen(req, timeout=10) as resp:
            code_resp = _json.loads(resp.read().decode("utf-8"))
    except (urllib.error.URLError, OSError):
        return None

    device_code = code_resp.get("device_code", "")
    user_code = code_resp.get("user_code", "")
    verification_uri = code_resp.get("verification_uri", "")
    verification_uri_complete = code_resp.get("verification_uri_complete", verification_uri)
    interval = int(str(code_resp.get("interval", 5)))
    expires_in = int(str(code_resp.get("expires_in", 900)))

    if not device_code or not user_code:
        return None

    # Step 2: Display URL immediately, then try browser in background thread
    if interactive:
        print()
        print(f"  {BOLD}Open this URL to authenticate:{NC}")
        print()
        print(f"    {GREEN}{verification_uri_complete}{NC}")
        print()
        # RFC 8628 UX: always show the user code so a headless/SSH user can
        # enter it manually at verification_uri, and anyone can confirm the
        # browser shows the SAME code before approving.
        print(f"    Code: {BOLD}{user_code}{NC}")
        if verification_uri and verification_uri != verification_uri_complete:
            print(f"    {DIM}(no browser? visit {verification_uri} and enter the code){NC}")
        print()

        def _open_bg() -> None:
            with contextlib.suppress(Exception):
                _wb.open(verification_uri_complete)

        _t = threading.Thread(target=_open_bg, daemon=True)
        _t.start()
        _t.join(timeout=2.0)
        if not _t.is_alive():
            print(f"  {DIM}(Browser opened \u2014 verify the code matches){NC}")
        else:
            print(f"  {DIM}(Opening browser...){NC}")

    # Step 3: Poll for token
    deadline = _time.monotonic() + expires_in
    poll_interval = interval

    while _time.monotonic() < deadline:
        _time.sleep(poll_interval)
        try:
            body = _json.dumps(
                {
                    "client_id": "trw-cli",
                    "device_code": device_code,
                    "grant_type": "urn:ietf:params:oauth:grant-type:device_code",
                }
            ).encode("utf-8")
            req = urllib.request.Request(
                f"{api_url}/v1/auth/device/token",
                data=body,
                method="POST",
                headers={"Content-Type": "application/json"},
            )
            with urllib.request.urlopen(req, timeout=10) as resp:
                return cast("dict[str, Any]", _json.loads(resp.read().decode("utf-8")))
        except urllib.error.HTTPError as exc:
            if exc.code >= 500:
                # Transient server error (e.g. mid-deploy 502/503): back off
                # and keep polling within the device-code deadline instead of
                # silently abandoning the whole device-auth flow.
                poll_interval = min(poll_interval * 2, 30)
                continue
            err_code = ""
            try:
                err_body = _json.loads(exc.read().decode("utf-8"))
                err_code = err_body.get("error", "")
            except Exception:
                pass
            if err_code == "authorization_pending":
                continue
            if err_code == "slow_down":
                poll_interval += 5
                continue
            return None  # trw-fail-silent-allow: expired_token, access_denied or any other code ends the flow; the caller reports the failed sign-in
        except (urllib.error.URLError, OSError):
            poll_interval = min(poll_interval * 2, 30)
            continue

    return None


